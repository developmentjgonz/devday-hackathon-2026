import { expect, test } from '@playwright/test'

test('a report draft and its attachments survive a cancelled close', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/iframe.html?id=pages-reports--review&viewMode=story')
  await page.evaluate((dark) => document.documentElement.classList.toggle('dark', dark), info.project.name === 'dark')
  const trigger = page.getByRole('button', { name: 'New report', exact: true })
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: 'New report' })
  const header = drawer.locator('[data-slot="drawer-header"]')
  await drawer.getByLabel('Colony', { exact: true }).selectOption('canal')
  await drawer.getByLabel('Cat (optional)').selectOption('miso')
  await expect(drawer.getByLabel('Cat (optional)')).toHaveValue('miso')
  const position = await header.boundingBox()
  await drawer.locator('[data-slot="drawer-body"]').evaluate((body) => { body.scrollTop = body.scrollHeight })
  expect(await header.boundingBox()).toEqual(position)
  await drawer.getByLabel('What happened?').fill('Water bowls need a refill')
  await drawer.getByLabel('Details').fill('The bowls are empty.')
  await drawer.getByLabel('Attachments (optional)').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('Care notes') })
  expect(await page.evaluate(() => { const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented })).toBe(true)
  await page.keyboard.press('Escape')
  const confirm = page.getByRole('dialog', { name: 'Discard changes?' })
  await expect(confirm.getByRole('button', { name: 'Keep editing' })).toBeFocused()
  await confirm.getByRole('button', { name: 'Keep editing' }).click()
  await expect(drawer.getByLabel('What happened?')).toHaveValue('Water bowls need a refill')
  await expect(drawer.getByText('notes.txt')).toBeVisible()
  await drawer.getByRole('button', { name: 'Cancel' }).click()
  await confirm.getByRole('button', { name: 'Discard changes' }).click()
  await expect(drawer).toBeHidden()
  await expect(trigger).toBeFocused()
  expect(await page.evaluate(() => { const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented })).toBe(false)
  await trigger.click()
  await expect(drawer.getByLabel('What happened?')).toHaveValue('')
  await expect(drawer.getByText('notes.txt')).toHaveCount(0)
})

test('task forms use a drawer and confirm before losing changes', async ({ page }, info) => {
  await page.setViewportSize({ width: 1024, height: 720 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/iframe.html?id=pages-my-tasks--focused-tasks&viewMode=story')
  await page.evaluate((dark) => document.documentElement.classList.toggle('dark', dark), info.project.name === 'dark')
  const trigger = page.getByRole('region', { name: 'Task controls' }).getByRole('button', { name: 'New task' })
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: 'New task' })
  await expect(drawer).toHaveAttribute('data-slot', 'drawer-content')
  await drawer.getByLabel('What needs to happen?').fill('Refill the water')
  await page.keyboard.press('Escape')
  const confirm = page.getByRole('dialog', { name: 'Discard changes?' })
  await page.keyboard.press('Escape')
  await expect(drawer.getByLabel('What needs to happen?')).toHaveValue('Refill the water')
  await drawer.getByRole('button', { name: 'Close new task' }).click()
  await confirm.getByRole('button', { name: 'Discard changes' }).click()
  await expect(drawer).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(drawer.getByLabel('What needs to happen?')).toHaveValue('')
  await drawer.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByRole('dialog', { name: 'Discard changes?' })).toHaveCount(0)
})

test('task context scrolls in the body while the compact header stays fixed', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 720 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const view of [
    { story: 'pages-my-tasks--focused-tasks', trigger: 'New task', title: 'New task', values: ['No colony', 'No cat'] },
  ]) {
    await page.goto(`/iframe.html?id=${view.story}&viewMode=story`)
    await page.getByRole('button', { name: view.trigger, exact: true }).click()
    const drawer = page.getByRole('dialog', { name: view.title, exact: true })
    const header = drawer.locator('[data-slot="drawer-header"]')
    const context = drawer.locator('[data-slot="drawer-body"] [data-slot="drawer-context"]')
    await expect(header.locator('[data-slot="drawer-context"]')).toHaveCount(0)
    for (const value of view.values) await expect(context).toContainText(value)
    const before = await header.boundingBox()
    await drawer.locator('[data-slot="drawer-body"]').evaluate((body) => { body.scrollTop = body.scrollHeight })
    await expect.poll(() => header.boundingBox()).toEqual(before)
    await expect(context).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
})

test('cat and team edits ask before discarding changes', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/iframe.html?id=pages-colonies-and-cats--cat&viewMode=story')
  await page.getByRole('button', { name: 'Edit profile' }).click()
  const cat = page.getByRole('dialog', { name: 'Edit cat profile' })
  const catHeader = cat.locator('[data-slot="drawer-header"]')
  await expect(catHeader.getByLabel('Colony', { exact: true })).toHaveCount(0)
  await expect(cat.locator('[data-slot="drawer-body"]').getByLabel('Colony', { exact: true })).toHaveValue('riverside')
  await cat.getByLabel('Cat name').fill('Pepper Two')
  await cat.getByRole('button', { name: 'Cancel' }).click()
  await page.getByRole('dialog', { name: 'Discard changes?' }).getByRole('button', { name: 'Keep editing' }).click()
  await expect(cat.getByLabel('Cat name')).toHaveValue('Pepper Two')
  await cat.getByRole('button', { name: 'Cancel' }).click()
  await page.getByRole('dialog', { name: 'Discard changes?' }).getByRole('button', { name: 'Discard changes' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Pepper' })).toBeVisible()

  await page.goto('/iframe.html?id=pages-team--team&viewMode=story')
  await page.getByRole('button', { name: 'Manage account: Sam Chen' }).click()
  const account = page.getByRole('dialog', { name: 'Account details' })
  await account.getByLabel('Role').selectOption('administrator')
  await account.getByRole('button', { name: 'Cancel' }).click()
  await page.getByRole('dialog', { name: 'Discard changes?' }).getByRole('button', { name: 'Keep editing' }).click()
  await expect(account.getByLabel('Role')).toHaveValue('administrator')
  await account.getByRole('button', { name: 'Close account details' }).click()
  await page.getByRole('dialog', { name: 'Discard changes?' }).getByRole('button', { name: 'Discard changes' }).click()
  await expect(account).toBeHidden()
})

test('in-app navigation asks before leaving an unfinished task', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/iframe.html?id=pages-my-tasks--focused-tasks&viewMode=story')
  await page.getByRole('region', { name: 'Task controls' }).getByRole('button', { name: 'New task' }).click()
  const drawer = page.getByRole('dialog', { name: 'New task' })
  await drawer.getByLabel('What needs to happen?').fill('Check the bowls')
  // A browser history change can navigate while the modal is open.
  const navigate = () => page.evaluate(() => (document.querySelector('a[href="/app/cats"]') as HTMLAnchorElement).click())
  await navigate()
  const confirm = page.getByRole('dialog', { name: 'Discard changes?' })
  await expect(confirm).toBeVisible()
  await confirm.getByRole('button', { name: 'Keep editing' }).click()
  await expect(drawer.getByLabel('What needs to happen?')).toHaveValue('Check the bowls')
  await navigate()
  await confirm.getByRole('button', { name: 'Discard changes' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Cats' })).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'New task' })).toHaveCount(0)
})
