test('location edits can be cancelled, saved, and cleared', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-colonies-and-cats--colony&viewMode=story')
  const location = page.getByRole('region', { name: 'Location' })
  const value = location.locator('[data-colony-location-value]')
  const original = await value.innerText()
  const map = location.getByRole('region', { name: 'Riverside location', exact: true })
  await expect(map.locator('[data-map-status="ready"]')).toBeVisible()
  await location.getByRole('button', { name: 'Edit location' }).click()
  let edit = page.getByRole('dialog', { name: 'Edit location' })
  await expect(edit.locator('[data-slot="drawer-context"]')).toContainText('Riverside')
  await edit.getByText('Coordinates and address details').click()
  await edit.getByLabel('Latitude').fill('25.765432')
  await edit.getByLabel('Longitude').fill('-80.234567')
  await edit.getByRole('button', { name: 'Cancel' }).click()
  await page.getByRole('dialog', { name: 'Discard changes?' }).getByRole('button', { name: 'Discard changes' }).click()
  await expect(value).toHaveText(original)
  await location.getByRole('button', { name: 'Edit location' }).click()
  edit = page.getByRole('dialog', { name: 'Edit location' })
  await edit.getByText('Coordinates and address details').click()
  await edit.getByLabel('Latitude').fill('25.765432')
  await edit.getByLabel('Longitude').fill('-80.234567')
  await edit.getByRole('button', { name: 'Save location' }).click()
  await expect(value).toHaveText('25.76543, -80.23457')
  await expect(map.locator('[data-map-status="ready"]')).toBeVisible()
  await location.getByRole('button', { name: 'Edit location' }).click()
  edit = page.getByRole('dialog', { name: 'Edit location' })
  await edit.getByText('Coordinates and address details').click()
  await expect(edit.getByLabel('Latitude')).toHaveValue('25.765432')
  await edit.getByRole('button', { name: 'Clear location' }).click()
  await edit.getByRole('button', { name: 'Save location' }).click()
  await expect(location.getByText('No location set')).toBeVisible()
  await expect(map).toHaveCount(0)
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Cats', exact: true }).click()
  await page.getByRole('group', { name: 'Cat view' }).getByRole('button', { name: 'Map' }).click()
  await expect(page.getByRole('heading', { name: 'Cats in colonies without a location' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Pepper', exact: true })).toBeVisible()
})

test('a colony created within a cat draft can use the device location on a phone', async ({ page, context }) => {
  await page.setViewportSize({ width: 320, height: 700 })
  await context.grantPermissions(['geolocation'])
  await context.setGeolocation({ latitude: 25.79, longitude: -80.21 })
  await page.goto('/iframe.html?id=pages-colonies-and-cats--cats&viewMode=story')
  await page.getByRole('button', { name: 'Add cat', exact: true }).click()
  const cat = page.getByRole('dialog', { name: 'Add cat' })
  await expect(cat.locator('[data-slot="drawer-body"]').getByLabel('Colony', { exact: true })).toBeVisible()
  await cat.getByLabel('Cat name').fill('Poppy')
  await expect(cat.getByLabel('Cat name')).toHaveValue('Poppy')
  await cat.getByRole('button', { name: 'Add colony' }).click()
  const colony = page.getByRole('dialog', { name: 'Add colony' })
  await expect(colony.locator('[data-slot="drawer-body"]')).toContainText('Create a colony for Poppy.')
  await colony.getByLabel('Colony name').fill('Garden')
  await expect(colony.getByLabel('Colony name')).toHaveValue('Garden')
  await colony.getByRole('button', { name: 'Add location (optional)' }).click()
  await colony.getByRole('button', { name: 'Use my location' }).click()
  await colony.getByText('Coordinates and address details').click()
  await expect(colony.getByLabel('Latitude')).toHaveValue('25.79')
  await expect(colony.getByLabel('Longitude')).toHaveValue('-80.21')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await colony.getByRole('button', { name: 'Add colony', exact: true }).click()
  await expect(cat.getByLabel('Cat name')).toHaveValue('Poppy')
  await expect(cat.getByLabel('Colony', { exact: true }).locator('option:checked')).toHaveText('Garden')
  await cat.getByRole('button', { name: 'Add cat', exact: true }).click()
  await (await openWorkspaceNavigation(page)).getByRole('link', { name: 'Colonies', exact: true }).click()
  await page.getByRole('link', { name: 'Garden', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Location' }).getByText('25.79000, -80.21000')).toBeVisible()
})

