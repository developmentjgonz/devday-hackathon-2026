test('the saved location remains available when its map cannot load', async ({ page }) => {
  await page.unroute('https://tiles.openfreemap.org/styles/positron')
  await page.route('https://tiles.openfreemap.org/styles/positron', (route) => route.abort())
  await page.goto('/iframe.html?id=pages-colonies-and-cats--colony&viewMode=story')
  const location = page.getByRole('region', { name: 'Location' })
  const map = location.getByRole('region', { name: 'Riverside location', exact: true })
  await map.scrollIntoViewIfNeeded()
  await expect(map.getByRole('alert')).toContainText('Map background unavailable')
  await expect(location.getByText('25.81200, -80.24900')).toBeVisible()
  await page.unroute('https://tiles.openfreemap.org/styles/positron')
  await page.route('https://tiles.openfreemap.org/styles/positron', (route) => route.fulfill({
    status: 200, contentType: 'application/json', body: JSON.stringify({ version: 8, sources: {}, layers: [] }),
  }))
  await map.getByRole('button', { name: 'Retry map' }).click()
  await expect(map.locator('[data-map-status="ready"]')).toBeVisible()
})
