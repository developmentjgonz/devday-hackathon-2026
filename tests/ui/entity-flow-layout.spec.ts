import { expect, test, type Locator, type Page } from '@playwright/test'

async function open(page: Page, story: string, width: number, dark: boolean) {
  await page.setViewportSize({ width, height: 720 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`/iframe.html?id=${story}&viewMode=story`)
  await page.evaluate((enabled) => document.documentElement.classList.toggle('dark', enabled), dark)
}
const header = (panel: Locator) => panel.locator('[data-slot="drawer-header"]')
async function height(panel: Locator) { return (await header(panel).boundingBox())!.height }

for (const width of [320, 390]) {
  test(`cat creation keeps its draft and header size across the colony step at ${width}px`, async ({ page }, info) => {
    await open(page, 'pages-colonies-and-cats--cats', width, info.project.name === 'dark')
    await page.getByRole('button', { name: 'Add cat', exact: true }).click()
    const cat = page.getByRole('dialog', { name: 'Add cat', exact: true })
    const initialHeight = await height(cat)
    await expect(header(cat).getByRole('combobox')).toHaveCount(0)
    await cat.getByLabel('Cat name').fill('Poppy')
    await cat.getByLabel('Details (optional)').fill('White paws and a clipped ear.')
    await cat.getByRole('button', { name: 'Add colony', exact: true }).click()
    const colony = page.getByRole('dialog', { name: 'Add colony', exact: true })
    expect(await height(colony)).toBeCloseTo(initialHeight, 0)
    const longName = 'TheVeryLongUnbrokenColonyNameThatMustNotResizeTheFixedHeader'
    await colony.getByLabel('Colony name').fill(longName)
    expect(await height(colony)).toBeCloseTo(initialHeight, 0)
    await colony.getByRole('button', { name: 'Back to cat' }).click()
    await expect(cat.getByLabel('Cat name')).toHaveValue('Poppy')
    await expect(cat.getByLabel('Details (optional)')).toHaveValue('White paws and a clipped ear.')
    await cat.getByRole('button', { name: 'Add colony', exact: true }).click()
    await expect(colony.getByLabel('Colony name')).toHaveValue(longName)
    await colony.getByRole('button', { name: 'Add colony', exact: true }).click()
    await expect(cat.getByLabel('Colony').locator('option:checked')).toHaveText(longName)
    expect(await height(cat)).toBeCloseTo(initialHeight, 0)
    await expect(cat.getByRole('button', { name: 'Add cat', exact: true })).toBeInViewport()
    expect((await cat.boundingBox())!.width).toBeGreaterThanOrEqual(width - 1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await cat.getByRole('button', { name: 'Add cat', exact: true }).click()
    await page.getByRole('link', { name: 'Poppy', exact: true }).click()
    await page.getByRole('button', { name: 'Edit profile' }).click()
    const edit = page.getByRole('dialog', { name: 'Edit cat profile' })
    expect(await height(edit)).toBeCloseTo(initialHeight, 0)
    await expect(edit.getByLabel('Details (optional)')).toHaveValue('White paws and a clipped ear.')
  })

  test(`task details and editing keep one header height as related items change at ${width}px`, async ({ page }, info) => {
    await open(page, 'pages-my-tasks--focused-tasks', width, info.project.name === 'dark')
    await page.getByRole('link', { name: 'View task: Arrange a care check' }).click()
    const task = page.getByRole('dialog', { name: 'Task', exact: true })
    const detailHeight = await height(task)
    const editTrigger = task.getByRole('button', { name: 'Edit task: Arrange a care check' })
    await editTrigger.click()
    const edit = page.getByRole('dialog', { name: 'Edit task', exact: true })
    expect(await height(edit)).toBeCloseTo(detailHeight, 0)
    await expect(header(edit).locator('[data-slot="drawer-context"]')).toHaveCount(0)
    const title = edit.getByLabel('What needs to happen?')
    const contentTop = () => title.evaluate((field) => {
      const body = field.closest('[data-slot="drawer-body"]')!
      return field.getBoundingClientRect().top - body.getBoundingClientRect().top + body.scrollTop
    })
    const originalTop = await contentTop()
    await edit.getByLabel('Choose cat').selectOption('miso')
    await edit.getByRole('button', { name: 'Add related item' }).click()
    await expect(edit.locator('[data-slot="drawer-body"] [data-slot="drawer-context"]')).toContainText('Riverside, Canal')
    expect(await height(edit)).toBeCloseTo(detailHeight, 0)
    expect(await contentTop()).toBeCloseTo(originalTop, 0)
    await edit.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
    await expect(editTrigger).toBeFocused()
    expect(await height(task)).toBeCloseTo(detailHeight, 0)
  })

  test(`colony membership actions keep focus in the panel at ${width}px`, async ({ page }, info) => {
    await open(page, 'pages-colonies-and-cats--colony', width, info.project.name === 'dark')
    await page.getByRole('button', { name: 'Manage cats' }).click()
    const panel = page.getByRole('dialog', { name: 'Manage cats' })
    await expect(header(panel).locator('[data-slot="drawer-context"]')).toHaveCount(0)
    const initialHeight = await height(panel)
    const select = panel.getByLabel('Cat', { exact: true })
    await select.selectOption('miso')
    await panel.getByRole('button', { name: 'Add existing cat' }).click()
    await expect(select).toBeFocused()
    await select.selectOption('olive')
    await panel.getByRole('button', { name: 'Add existing cat' }).click()
    const members = panel.getByRole('heading', { name: 'Cats in this colony' })
    await expect(members).toBeFocused()
    await panel.getByRole('button', { name: 'Remove Miso from Riverside' }).click()
    await expect(members).toBeFocused()
    expect(await height(panel)).toBeCloseTo(initialHeight, 0)
    await panel.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Manage cats', exact: true })).toBeFocused()
    const location = page.getByRole('button', { name: 'Edit location', exact: true })
    await location.scrollIntoViewIfNeeded()
    const before = await page.evaluate(() => scrollY)
    await location.click()
    const editor = page.getByRole('dialog', { name: 'Edit location' })
    expect(await height(editor)).toBeCloseTo(initialHeight, 0)
    await expect(header(editor).locator('[data-slot="drawer-context"]')).toHaveCount(0)
    await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(location).toBeFocused()
    expect(await page.evaluate(() => scrollY)).toBeCloseTo(before, 0)
  })
}
