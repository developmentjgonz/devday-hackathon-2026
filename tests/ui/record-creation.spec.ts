import { expect, test } from '@playwright/test'

const story = '/iframe.html?id=pages-colonies-and-cats--colonies&viewMode=story'

test('a report created from a cat opens without leaving the cat page', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-my-tasks--focused-tasks&viewMode=story')
  await page.getByRole('link', { name: 'Open cat: Pepper', exact: true }).click()
  const trigger = page.getByRole('button', { name: 'New report', exact: true })
  await trigger.click()
  const form = page.getByRole('dialog', { name: 'New report' })
  await form.getByLabel('What happened?').fill('Pepper had fresh water')
  await form.getByLabel('Details').fill('The water bowl was full.')
  await form.getByRole('button', { name: 'Submit report' }).click()
  const report = page.getByRole('dialog', { name: 'Report', exact: true })
  await expect(report.getByText('Pepper had fresh water', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('heading', { level: 1, name: 'Pepper', exact: true })).toBeVisible()
  await expect(trigger).toBeFocused()
})

test('new colonies and cats are available across the workspace', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(story)
  await page.evaluate((dark) => document.documentElement.classList.toggle('dark', dark), info.project.name === 'dark')
  await page.getByRole('searchbox', { name: 'Search colonies' }).fill('no matching colony')
  await page.getByRole('region', { name: 'Colony controls' }).getByRole('button', { name: 'Add colony' }).click()
  const colonyDialog = page.getByRole('dialog', { name: 'Add colony' })
  await expect(colonyDialog.getByRole('button', { name: 'Add colony', exact: true })).toBeDisabled()
  await colonyDialog.getByLabel('Colony name').fill('  Garden  ')
  await colonyDialog.getByRole('button', { name: 'Add colony', exact: true }).click()
  await expect(page.getByRole('searchbox', { name: 'Search colonies' })).toHaveValue('')
  await expect(page.getByText('Colony added', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Garden', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Garden' })).toBeVisible()
  await page.getByRole('button', { name: 'Add cat', exact: true }).click()
  const catDialog = page.getByRole('dialog', { name: 'Add cat' })
  await expect(catDialog.getByText('Add a cat to Garden.')).toBeVisible()
  await catDialog.getByLabel('Cat name').fill('Poppy')
  await catDialog.getByRole('button', { name: 'Add cat', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Poppy', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Poppy', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Poppy' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Garden', exact: true }).last()).toBeVisible()
  const nav = page.getByRole('navigation', { name: 'Workspace navigation' })
  await nav.getByRole('link', { name: 'Reports', exact: true }).click()
  await page.getByRole('region', { name: 'Report controls' }).getByRole('button', { name: 'New report' }).click()
  const report = page.getByRole('dialog', { name: 'New report' })
  await report.getByLabel('Colony', { exact: true }).selectOption({ label: 'Garden' })
  await expect(report.getByLabel('Cat (optional)')).toContainText('Poppy')
})

test('adding a cat from the directory clears filters that would hide it', async ({ page }) => {
  await page.goto(story)
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Cats', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search cats' }).fill('no matching cat')
  await page.getByLabel('Colony', { exact: true }).selectOption('canal')
  await page.getByRole('region', { name: 'Cat controls' }).getByRole('button', { name: 'Add cat' }).click()
  const dialog = page.getByRole('dialog', { name: 'Add cat' })
  await expect(dialog.getByLabel('Colony')).toHaveValue('canal')
  await dialog.getByLabel('Cat name').fill('Marmalade')
  await dialog.getByRole('button', { name: 'Add cat', exact: true }).click()
  await expect(page.getByRole('searchbox', { name: 'Search cats' })).toHaveValue('')
  await expect(page.getByRole('region', { name: 'Cat controls' }).getByLabel('Colony', { exact: true })).toHaveValue('all')
  await expect(page.getByRole('link', { name: 'Marmalade', exact: true })).toBeVisible()
})

test('a colony can be created without leaving a new cat draft', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/iframe.html?id=pages-colonies-and-cats--no-colonies&viewMode=story')
  const trigger = page.getByRole('region', { name: 'Cat controls' }).getByRole('button', { name: 'Add cat' })
  await trigger.click()
  const catDialog = page.getByRole('dialog', { name: 'Add cat' })
  await catDialog.getByLabel('Cat name').fill('Poppy')
  await expect(catDialog.getByRole('button', { name: 'Add cat', exact: true })).toBeDisabled()
  await catDialog.getByRole('button', { name: 'Add colony' }).click()
  const colonyDialog = page.getByRole('dialog', { name: 'Add colony' })
  await expect(page.locator('[data-slot="drawer-content"]')).toHaveCount(1)
  await colonyDialog.getByLabel('Colony name').fill('Garden')
  await page.keyboard.press('Escape')
  await expect(catDialog.getByLabel('Cat name')).toHaveValue('Poppy')
  await expect(catDialog.getByRole('button', { name: 'Add colony' })).toBeFocused()
  await catDialog.getByRole('button', { name: 'Add colony' }).click()
  await expect(colonyDialog.getByLabel('Colony name')).toHaveValue('Garden')
  await colonyDialog.getByRole('button', { name: 'Add colony' }).click()
  await expect(colonyDialog).toHaveCount(0)
  await expect(catDialog.getByLabel('Cat name')).toHaveValue('Poppy')
  const colonyId = await catDialog.getByRole('option', { name: 'Garden' }).getAttribute('value')
  await expect(catDialog.getByLabel('Colony')).toHaveValue(colonyId!)
  await catDialog.getByRole('button', { name: 'Add cat', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Poppy', exact: true })).toBeVisible()
})

test('a failed save keeps the form and its entered name available', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-colonies-and-cats--save-failure&viewMode=story')
  await page.getByRole('region', { name: 'Colony controls' }).getByRole('button', { name: 'Add colony' }).click()
  const dialog = page.getByRole('dialog', { name: 'Add colony' })
  await dialog.getByLabel('Colony name').fill('Garden')
  const save = dialog.getByRole('button', { name: 'Add colony', exact: true })
  await save.click()
  await expect(save).toHaveAttribute('aria-busy', 'true')
  await expect(dialog.getByRole('button', { name: 'Cancel' })).toBeDisabled()
  await expect(dialog.getByRole('alert')).toContainText('The directory is unavailable')
  await expect(dialog.getByLabel('Colony name')).toHaveValue('Garden')
  await expect(save).toBeEnabled()
  await expect(page.getByRole('link', { name: 'Garden', exact: true })).toHaveCount(0)
})
