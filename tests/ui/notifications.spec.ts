import { expect, test, type Page } from '@playwright/test'

async function openStory(page: Page, story: string, dark: boolean) {
  await page.clock.setFixedTime(new Date('2026-11-07T17:00:00Z'))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.route('https://images.unsplash.com/**', (route) => route.abort())
  await page.goto(`/iframe.html?id=pages-notifications--${story}&viewMode=story`, { waitUntil: 'domcontentloaded' })
  await page.evaluate((isDark) => document.documentElement.classList.toggle('dark', isDark), dark)
}

test('drawer groups attention items and maintains read state', async ({ page }, info) => {
  await openStory(page, 'default', info.project.name === 'dark')
  const bell = page.getByRole('button', { name: 'Notifications: 6' })
  await bell.focus()
  await page.keyboard.press('Enter')
  const drawer = page.getByRole('dialog', { name: 'Notifications' })
  await expect(drawer).toBeVisible()
  await expect(drawer.getByRole('heading', { name: 'Urgent reports' })).toBeVisible()
  await expect(drawer.getByRole('heading', { name: 'Unread reports' })).toBeVisible()
  await expect(drawer.getByRole('heading', { name: 'Your tasks due' })).toBeVisible()
  await expect(drawer.getByText('Bring food tomorrow')).toHaveCount(0)
  await expect(drawer.getByText('Another member’s task')).toHaveCount(0)
  await expect(drawer.getByText('Finished task')).toHaveCount(0)
  await drawer.getByRole('button', { name: 'Mark Orange cat by the Canal entrance as read' }).click()
  await expect(drawer.getByText('Orange cat by the Canal entrance')).toHaveCount(0)
  await expect(page.locator('button[title="Notifications"]')).toHaveAttribute('aria-label', 'Notifications: 5')
  await drawer.getByRole('button', { name: 'Mark all reports as read' }).click()
  await expect(drawer.getByRole('heading', { name: 'Unread reports' })).toHaveCount(0)
  await expect(drawer.getByText('Possible injury near the feeding station')).toBeVisible()
  await expect(drawer.getByText('Three kittens spotted behind the shed')).toBeVisible()
  await expect(page.locator('button[title="Notifications"]')).toHaveAttribute('aria-label', 'Notifications: 4')
  await page.keyboard.press('Escape')
  await expect(drawer).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Notifications: 4' })).toBeFocused()
  await page.getByRole('button', { name: 'Notifications: 4' }).click()
  await expect(drawer.getByRole('heading', { name: 'Unread reports' })).toHaveCount(0)
})

test('report and task notifications open the selected records', async ({ page }, info) => {
  await openStory(page, 'default', info.project.name === 'dark')
  await page.getByRole('button', { name: /Notifications:/ }).click()
  const drawer = page.getByRole('dialog', { name: 'Notifications' })
  await drawer.getByRole('link', { name: /Possible injury near the feeding station/ }).click()
  const report = page.getByRole('dialog', { name: 'Possible injury near the feeding station' })
  await expect(report).toBeVisible()
  await expect(drawer).not.toBeVisible()
  await report.getByRole('button', { name: 'Close report' }).click()
  await page.getByRole('button', { name: /Notifications:/ }).click()
  await drawer.getByRole('link', { name: /Call the clinic/ }).click()
  await expect(drawer).not.toBeVisible()
  await expect(page.getByRole('heading', { level: 1, name: 'My Tasks' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Call the clinic' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Check the shelter' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.getByRole('heading', { name: 'Check the shelter' })).toBeVisible()
})

test('empty, refresh failure, and read failure states recover', async ({ page }, info) => {
  await openStory(page, 'empty', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Notifications: 0' }).click()
  await expect(page.getByRole('heading', { name: 'No notifications' })).toBeVisible()

  await openStory(page, 'refresh-error', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Notifications: 0' }).click()
  await expect(page.getByRole('heading', { name: 'Notifications unavailable' })).toBeVisible()
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByRole('heading', { name: 'No notifications' })).toBeVisible()

  await openStory(page, 'read-error', info.project.name === 'dark')
  await page.getByRole('button', { name: /Notifications:/ }).click()
  const drawer = page.getByRole('dialog', { name: 'Notifications' })
  const mark = drawer.getByRole('button', { name: 'Mark Orange cat by the Canal entrance as read' })
  await mark.click()
  await expect(drawer.getByRole('alert')).toContainText('Could not mark')
  await expect(drawer.getByText('Orange cat by the Canal entrance')).toBeVisible()
  await mark.click()
  await expect(drawer.getByText('Orange cat by the Canal entrance')).toHaveCount(0)
  await expect(drawer.getByRole('alert')).toHaveCount(0)
})

test('a stale refresh cannot undo a read update', async ({ page }, info) => {
  await openStory(page, 'stale-refresh', info.project.name === 'dark')
  await page.getByRole('button', { name: /Notifications:/ }).click()
  const drawer = page.getByRole('dialog', { name: 'Notifications' })
  await drawer.getByRole('button', { name: 'Mark Orange cat by the Canal entrance as read' }).click()
  await page.waitForTimeout(1900)
  await expect(drawer.getByText('Orange cat by the Canal entrance')).toHaveCount(0)
})

test('refresh finds new reports and bulk read handles more than one API batch', async ({ page }, info) => {
  await openStory(page, 'incoming-report', info.project.name === 'dark')
  await expect(page.getByRole('button', { name: 'Notifications: 0' })).toBeVisible()
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(page.getByRole('button', { name: 'Notifications: 1' })).toBeVisible()
  await page.getByRole('button', { name: 'Notifications: 1' }).click()
  await expect(page.getByRole('dialog', { name: 'Notifications' }).getByText('New feeding update')).toBeVisible()

  await openStory(page, 'many-reports', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Notifications: 105' }).click()
  await page.getByRole('dialog', { name: 'Notifications' }).getByRole('button', { name: 'Mark all reports as read' }).click()
  await expect(page.getByRole('heading', { name: 'No notifications' })).toBeVisible()
  await expect(page.locator('button[title="Notifications"]')).toHaveAttribute('aria-label', 'Notifications: 0')
})

test('bulk read keeps successful batches when a later request fails', async ({ page }, info) => {
  await openStory(page, 'bulk-read-error', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Notifications: 105' }).click()
  const drawer = page.getByRole('dialog', { name: 'Notifications' })
  await drawer.getByRole('button', { name: 'Mark all reports as read' }).click()
  await expect(drawer.getByRole('alert')).toContainText('100 reports marked as read. Could not update the rest.')
  await expect(page.locator('button[title="Notifications"]')).toHaveAttribute('aria-label', 'Notifications: 5')
  await drawer.getByRole('button', { name: 'Mark all reports as read' }).click()
  await expect(drawer.getByRole('heading', { name: 'No notifications' })).toBeVisible()
})

