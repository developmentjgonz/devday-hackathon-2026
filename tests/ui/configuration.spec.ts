import { expect, test } from '@playwright/test'

const story = (name: string) => `/iframe.html?id=pages-configuration--${name}&viewMode=story`

test('administrators can edit, save, and restore the report chat prompt', async ({ page }) => {
  await page.goto(story('ai-analysis'))
  const prompt = page.getByLabel('Report chat system prompt', { exact: true })
  const original = await prompt.inputValue()
  expect(original).toContain('warm, attentive assistant')
  await prompt.fill('Be kind. Ask one question at a time. Thank people for helping cats.')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
  await page.getByRole('link', { name: 'Communication setup', exact: true }).click()
  await page.getByRole('link', { name: 'AI analysis', exact: true }).click()
  await expect(prompt).toHaveValue('Be kind. Ask one question at a time. Thank people for helping cats.')
  await page.getByRole('button', { name: 'Restore default prompt', exact: true }).click()
  await expect(prompt).toHaveValue(original)
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
})

test.beforeEach(async ({ page }, info) => {
  await page.addInitScript((dark) => {
    window.addEventListener('DOMContentLoaded', () => document.documentElement.classList.toggle('dark', dark), { once: true })
  }, info.project.name === 'dark')
})

test('administrators can enable contact options, retain details when disabled, and manage a write-only key', async ({ page }) => {
  await page.goto(story('communication-setup'))
  const navigation = page.getByRole('navigation', { name: 'Configuration sections' })
  await expect(page.getByText('People contact this number directly. Calls and texts do not appear in Mews.')).toBeVisible()
  await expect(page.getByText('People email this address directly. Emails do not appear in Mews.')).toBeVisible()
  const phoneSwitch = page.getByRole('switch', { name: 'Show phone number on the public report form' })
  const emailSwitch = page.getByRole('switch', { name: 'Show email address on the public report form' })
  await expect(phoneSwitch).not.toBeChecked()
  await expect(emailSwitch).not.toBeChecked()
  await phoneSwitch.click()
  await emailSwitch.click()
  await page.getByLabel('Phone number', { exact: true }).fill('+1 (305) 555-0123')
  await page.getByLabel('Email address', { exact: true }).fill('REPORTS@example.test')
  await navigation.getByRole('link', { name: 'AI analysis' }).click()
  await expect(page.getByRole('heading', { name: 'AI analysis', exact: true })).toBeVisible()
  await navigation.getByRole('link', { name: 'Communication setup' }).click()
  await expect(page.getByRole('heading', { name: 'Communication setup', exact: true })).toBeVisible()
  await expect(page.getByLabel('Phone number', { exact: true })).toHaveValue('+1 (305) 555-0123')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByLabel('Email address', { exact: true })).toHaveValue('reports@example.test')
  await phoneSwitch.click()
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(phoneSwitch).not.toBeChecked()
  await expect(emailSwitch).toBeChecked()
  await expect(page.getByLabel('Phone number', { exact: true })).toHaveValue('+1 (305) 555-0123')
  await navigation.getByRole('link', { name: 'AI analysis' }).click()
  await page.getByLabel('OpenAI model').fill('example-model')
  const key = page.getByLabel('OpenAI API key')
  await key.fill('fictional-test-key')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(key).toHaveValue('')
  await expect(page.getByText('A key is saved. Enter a new key to replace it.')).toBeVisible()
  await page.getByRole('button', { name: 'Remove key' }).click()
  await expect(page.getByText('No API key is saved.')).toBeVisible()
})

test('configuration works on a phone and is restricted to administrators', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 844 })
  await page.goto(story('member-access'))
  await expect(page.getByText('Administrator access required')).toBeVisible()
  await expect(page.getByLabel('Phone number', { exact: true })).toHaveCount(0)
  await page.goto(story('communication-setup'))
  await expect(page.getByRole('link', { name: 'Open report form' })).toHaveAttribute('href', '/report')
  await expect(page.getByRole('img', { name: 'QR code for the public report chat' })).toBeVisible()
  const headings = await page.locator('main h3').allTextContents()
  expect(headings.slice(0, 3)).toEqual(['Online reports', 'Phone', 'Email'])
  await expect(page.getByText('This link only works on this device. Open your public site to make a QR code for others.')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download QR code' }).click()
  expect((await download).suggestedFilename()).toBe('mews-report-qr.png')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

