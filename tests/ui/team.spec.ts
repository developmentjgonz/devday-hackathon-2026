import { expect, test, type Page } from '@playwright/test'

const story = (name: string) => `/iframe.html?id=pages-team--${name}&viewMode=story`
async function openStory(page: Page, name: string, dark: boolean) {
  await page.goto(story(name))
  await page.evaluate((enabled) => document.documentElement.classList.toggle('dark', enabled), dark)
  await page.getByRole('banner', { name: 'Workspace header' }).waitFor({ state: 'visible', timeout: 30000 })
}
test.setTimeout(60000)

test('reviews requests, filters accounts, and returns focus after approval', async ({ page }, info) => {
  await openStory(page, 'team', info.project.name === 'dark')
  const navigation = page.getByRole('navigation', { name: 'Workspace navigation' })
  await expect(navigation.getByRole('link', { name: 'Team', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(page.getByRole('heading', { name: '2 people are waiting to join' })).toBeVisible()
  await page.getByRole('button', { name: 'Review requests' }).click()
  await expect(page.getByLabel('Filter accounts by access')).toHaveValue('pending')
  await expect(page.getByRole('row', { name: /Jordan Lee/ })).toBeVisible()
  await expect(page.getByRole('row', { name: /Sam Chen/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Review account: Jordan Lee' }).click()
  const drawer = page.getByRole('dialog', { name: 'Review access request' })
  await expect(drawer.getByText('(305) 555-0154')).toBeVisible()
  await drawer.getByRole('button', { name: 'Approve access' }).click()
  await expect(drawer).toBeHidden()
  await expect(page.getByRole('heading', { name: '1 person is waiting to join' })).toBeVisible()
  await expect(page.getByRole('row', { name: /Jordan Lee/ })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Team accounts', exact: true }).last()).toBeFocused()
  await page.getByRole('button', { name: 'View all accounts' }).click()
  const jordan = page.getByRole('row', { name: /Jordan Lee/ })
  await expect(jordan).toContainText('Active')
  await page.getByLabel('Search team accounts').fill('jordan@mews')
  await expect(jordan).toBeVisible()
  await expect(page.getByRole('row', { name: /Devon James/ })).toHaveCount(0)
  await page.getByLabel('Search team accounts').fill('nobody')
  await expect(page.getByRole('heading', { name: 'No matching accounts' })).toBeVisible()
})

test('changes role and access while keeping the signed-in account access read-only', async ({ page }, info) => {
  await openStory(page, 'team', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Manage account: Sam Chen' }).click()
  const drawer = page.getByRole('dialog', { name: 'Account details' })
  await drawer.getByLabel('Role').selectOption('administrator')
  await drawer.getByLabel('Access', { exact: true }).selectOption('suspended')
  await expect(drawer.getByText('This person cannot enter the workspace while access is suspended.')).toBeVisible()
  await drawer.getByRole('button', { name: 'Save changes' }).click()
  await expect(drawer).toBeHidden()
  const row = page.getByRole('row', { name: /Sam Chen/ })
  await expect(row).toContainText('Administrator')
  await expect(row).toContainText('Suspended')
  await page.getByRole('button', { name: 'Manage account: Alex Morgan' }).click()
  await expect(drawer.getByText('Another administrator must change your access.')).toBeVisible()
  await expect(drawer.getByRole('button', { name: 'Save changes' })).toBeDisabled()
  await drawer.getByLabel('Available for tasks').selectOption('disabled')
  await drawer.getByRole('button', { name: 'Save changes' }).click()
  await page.getByRole('button', { name: 'Manage account: Alex Morgan' }).click()
  await expect(drawer.getByLabel('Available for tasks')).toHaveValue('disabled')
  await drawer.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Manage account: Alex Morgan' })).toBeFocused()
})

test('task assignment setting updates the task choices and can be restored', async ({ page }, info) => {
  await openStory(page, 'team', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Manage account: Sam Chen' }).click()
  let drawer = page.getByRole('dialog', { name: 'Account details' })
  await drawer.getByLabel('Available for tasks').selectOption('disabled')
  await drawer.getByRole('button', { name: 'Save changes' }).click()
  await page.getByRole('button', { name: 'Manage account: Sam Chen' }).click()
  await expect(drawer.getByLabel('Available for tasks')).toHaveValue('disabled')
  await drawer.getByRole('button', { name: 'Cancel' }).click()
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'My Tasks' }).click()
  await page.getByRole('region', { name: 'Task controls' }).getByRole('button', { name: 'New task' }).click()
  let task = page.getByRole('dialog', { name: 'New task' })
  await expect(task.getByLabel('Assign to').locator('option').filter({ hasText: 'Sam Chen' })).toHaveCount(0)
  await expect(task.getByLabel('Assign to').locator('option').filter({ hasText: 'Alex Morgan' })).toHaveCount(1)
  await task.getByRole('button', { name: 'Cancel' }).click()
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Team', exact: true }).click()
  await page.getByRole('button', { name: 'Manage account: Sam Chen' }).click()
  drawer = page.getByRole('dialog', { name: 'Account details' })
  await drawer.getByLabel('Available for tasks').selectOption('enabled')
  await drawer.getByRole('button', { name: 'Save changes' }).click()
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'My Tasks' }).click()
  await page.getByRole('region', { name: 'Task controls' }).getByRole('button', { name: 'New task' }).click()
  task = page.getByRole('dialog', { name: 'New task' })
  await expect(task.getByLabel('Assign to').locator('option').filter({ hasText: 'Sam Chen' })).toHaveCount(1)
})

test('handles denied access and load or save failures', async ({ page }, info) => {
  await openStory(page, 'member-access', info.project.name === 'dark')
  await expect(page.getByRole('heading', { name: 'Administrator access required' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Team', exact: true })).toHaveCount(0)
  await openStory(page, 'load-error', info.project.name === 'dark')
  await expect(page.getByRole('heading', { name: 'Could not load team accounts' })).toBeVisible()
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByRole('heading', { name: 'Could not load team accounts' })).toBeVisible()
  await openStory(page, 'save-error', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Review account: Jordan Lee' }).click()
  const drawer = page.getByRole('dialog', { name: 'Review access request' })
  await drawer.getByRole('button', { name: 'Approve access' }).click()
  await expect(drawer.getByRole('alert')).toContainText('Could not update access')
  await expect(drawer.getByRole('button', { name: 'Approve access' })).toBeEnabled()
  await drawer.getByRole('button', { name: 'Refresh team list' }).click()
  await expect(drawer).toBeHidden()
  await expect(page.getByRole('heading', { name: '2 people are waiting to join' })).toBeVisible()
})

test('supports pagination and an empty result', async ({ page }, info) => {
  await openStory(page, 'many-accounts', info.project.name === 'dark')
  await expect(page.getByText('1–10 of 18 accounts')).toBeVisible()
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.getByText('11–18 of 18 accounts')).toBeVisible()
  await page.getByLabel('Filter accounts by access').selectOption('pending')
  await expect(page.getByText('2 accounts', { exact: true }).first()).toBeVisible()
  await openStory(page, 'empty', info.project.name === 'dark')
  await expect(page.getByRole('heading', { name: 'No team accounts' })).toBeVisible()
})

