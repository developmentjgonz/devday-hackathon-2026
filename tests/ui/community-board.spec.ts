import { expect, test } from '@playwright/test'

test('an administrator can add a section, publish a post, edit it, retire it, and restore it', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-community-board--administrator&viewMode=story')
  await page.getByRole('button', { name: 'Add section', exact: true }).click()
  await page.getByLabel('Section name').fill('Supply drives')
  await page.getByRole('dialog').getByRole('button', { name: 'Add section', exact: true }).click()
  const section = page.getByRole('region', { name: 'Supply drives', exact: true })
  await expect(section).toBeVisible()
  await section.getByRole('button', { name: 'Add post to Supply drives', exact: true }).click()
  await page.getByLabel('Post title', { exact: true }).fill('Winter blankets')
  await page.getByLabel('Details', { exact: true }).fill('Bring clean blankets to the supply table.')
  await page.getByRole('button', { name: 'Publish post', exact: true }).click()
  const post = page.getByRole('article', { name: 'Winter blankets', exact: true })
  await expect(post).toContainText('Bring clean blankets')
  await post.getByRole('button', { name: 'Edit post: Winter blankets', exact: true }).click()
  await page.getByLabel('Post title', { exact: true }).fill('Winter supplies')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await page.getByRole('button', { name: 'Retire post: Winter supplies', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Winter supplies', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Retired', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Winter supplies', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Restore post: Winter supplies', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'No retired posts', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Published', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Winter supplies', exact: true })).toContainText('Bring clean blankets')
})

test('save errors keep the post form and entered details', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-community-board--save-error&viewMode=story')
  await page.getByRole('button', { name: 'Add post to Community news', exact: true }).click()
  await page.getByLabel('Post title', { exact: true }).fill('Supply day')
  await page.getByLabel('Details', { exact: true }).fill('Meet at noon.')
  await page.getByRole('button', { name: 'Publish post', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Could not save the board')
  await expect(page.getByLabel('Post title', { exact: true })).toHaveValue('Supply day')
  await expect(page.getByLabel('Details', { exact: true })).toHaveValue('Meet at noon.')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Discard changes?' })).toBeVisible()
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(page.getByLabel('Details', { exact: true })).toHaveValue('Meet at noon.')
})

test('members cannot open board controls', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-community-board--member-access&viewMode=story')
  await expect(page.getByRole('heading', { name: 'Administrator access required', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Add section', exact: true })).toHaveCount(0)
})
