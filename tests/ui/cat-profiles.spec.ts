import { expect, test } from '@playwright/test'

const pixel = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZYAAAAASUVORK5CYII=', 'base64')

test('create and edit a cat profile with optional age, details and photo', async ({ page }, info) => {
  await page.goto('/iframe.html?id=pages-colonies-and-cats--cats&viewMode=story')
  await page.evaluate((dark) => document.documentElement.classList.toggle('dark', dark), info.project.name === 'dark')
  await page.getByRole('region', { name: 'Cat controls' }).getByRole('button', { name: 'Add cat' }).click()
  const add = page.getByRole('dialog', { name: 'Add cat' })
  await add.getByLabel('Cat name').fill('Poppy')
  await add.getByLabel('Colony', { exact: true }).selectOption('canal')
  await add.getByLabel('Birth date (optional)').fill('2021-03-12')
  await add.getByRole('checkbox', { name: 'This date is an estimate' }).check()
  await add.getByLabel('Details (optional)').fill('White paws and a quiet meow')
  await add.getByLabel('Cat photo (optional)').setInputFiles({ name: 'poppy.png', mimeType: 'image/png', buffer: pixel })
  await expect(add.getByRole('img', { name: 'Poppy photo' })).toBeVisible()
  await add.getByRole('button', { name: 'Add cat', exact: true }).click()
  await page.getByRole('link', { name: 'Poppy', exact: true }).click()
  await expect(page.getByText('Estimated birth date')).toBeVisible()
  await expect(page.getByText('March 12, 2021')).toBeVisible()
  await expect(page.getByText('White paws and a quiet meow')).toBeVisible()
  await expect(page.getByRole('img', { name: 'Poppy photo' })).toBeVisible()
  await page.getByRole('button', { name: 'Edit profile' }).click()
  const edit = page.getByRole('dialog', { name: 'Edit cat profile' })
  await edit.getByLabel('Details (optional)').fill('White paws and a clipped ear')
  await edit.getByRole('button', { name: 'Remove photo' }).click()
  await edit.getByRole('checkbox', { name: 'This date is an estimate' }).uncheck()
  await edit.getByRole('button', { name: 'Save profile' }).click()
  await expect(page.getByRole('region', { name: 'Details' }).getByText('White paws and a clipped ear', { exact: true })).toBeVisible()
  await expect(page.getByText('Birth date', { exact: true })).toBeVisible()
  await expect(page.getByRole('main').getByRole('img', { name: 'Poppy, no photo' })).toBeVisible()
})

test('photo validation keeps the profile form open', async ({ page }) => {
  await page.route('**/photo-1514888286974-6c03e2ca1dba**', (route) => route.fulfill({ status: 200, contentType: 'image/png', body: pixel }))
  await page.goto('/iframe.html?id=pages-colonies-and-cats--cat&viewMode=story')
  await page.getByRole('button', { name: 'Edit profile' }).click()
  const edit = page.getByRole('dialog', { name: 'Edit cat profile' })
  await edit.getByLabel('Cat photo (optional)').setInputFiles({ name: 'bad.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') })
  await expect(edit.getByRole('alert')).toContainText('JPEG, PNG, or WebP')
  await expect(edit.getByRole('button', { name: 'Save profile' })).toBeDisabled()
  await edit.getByRole('button', { name: 'Clear photo error' }).click()
  await expect(edit.getByRole('img', { name: 'Pepper photo' })).toBeVisible()
  await expect(edit.getByRole('button', { name: 'Save profile' })).toBeEnabled()
})

test('large cat photos are resized before they are saved', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-colonies-and-cats--cat&viewMode=story')
  await page.getByRole('button', { name: 'Edit profile' }).click()
  const edit = page.getByRole('dialog', { name: 'Edit cat profile' })
  await edit.getByLabel('Cat photo (optional)').setInputFiles({ name: 'large.png', mimeType: 'image/png', buffer: Buffer.concat([pixel, Buffer.alloc(1024 * 1024)]) })
  await expect(edit.getByRole('img', { name: 'Pepper photo' })).toBeVisible()
  await expect(edit.getByRole('button', { name: 'Save profile' })).toBeEnabled()
  await edit.getByRole('button', { name: 'Save profile' }).click()
  const image = page.getByRole('region', { name: 'Details' }).getByRole('img', { name: 'Pepper photo' }).locator('img')
  await expect(image).toHaveAttribute('src', /^data:image\/jpeg;base64,/)
})

