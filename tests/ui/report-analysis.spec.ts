  await expect(context).toContainText('Pepper')
  await page.getByLabel('What needs to happen?').fill('Check Pepper at the fence')
  await page.getByLabel('Assign to').selectOption({ label: 'Sam Chen' })
  await page.getByRole('dialog', { name: 'Create a care task' }).getByRole('button', { name: 'Create task', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Possible tasks' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Back to report' }).click()
  await expect(page.getByRole('region', { name: /Care tasks/ })).toContainText('Check Pepper at the fence')
  await page.getByRole('button', { name: 'Create task', exact: true }).click()
  await expect(page.getByLabel('What needs to happen?')).toHaveValue('Unfinished manual task')
  await page.keyboard.press('Escape')
  await openSuggestions(page)
  await page.getByRole('button', { name: 'Add cat: Cat with a possible injury.' }).click()
