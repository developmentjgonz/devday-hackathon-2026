test('empty, failed, and disabled analysis keep the report usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(story('no-ai-suggestions'))
  await expect(page.getByRole('button', { name: 'View AI analysis' })).toBeVisible()
  await openSuggestions(page)
  await expect(page.getByRole('heading', { name: 'No suggestions' })).toBeVisible()
  await page.getByRole('button', { name: 'Back to report' }).click()
  await expect(await careNote(page)).toHaveValue('Reported limping on a front paw and reduced interest in food. Needs a care check.')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto(story('ai-analysis-retry'))
  await expect(page.getByRole('button', { name: 'View AI analysis' })).toBeVisible()
  await openSuggestions(page)
  await expect(page.getByText('Report analysis is unavailable. Try again.')).toBeVisible()
  await page.getByRole('button', { name: 'Try again', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Possible tasks' })).toBeVisible()
  await page.goto(story('report-drawer'))
  await expect(page.getByRole('heading', { name: 'AI suggestions' })).toHaveCount(0)
  await expect(await careNote(page)).toBeVisible()
})

