test('a task stays linked after saving and reopening the report', async ({ page }, info) => {
  await open(page, 'pages-reports--report-drawer', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Create task', exact: true }).click()
  await page.getByLabel('What needs to happen?', { exact: true }).fill('Check Pepper at the fence')
  await page.getByLabel('Assign to', { exact: true }).selectOption({ label: 'Sam Chen' })
  await page.getByLabel('Due date (optional)', { exact: true }).fill('2026-11-08')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Create task', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Create task', exact: true }).click()
  await expect(page.getByLabel('What needs to happen?', { exact: true })).toHaveValue('Check Pepper at the fence')
  await expect(page.getByLabel('Assign to', { exact: true }).locator('option:checked')).toHaveText('Sam Chen')
  await page.getByRole('dialog', { name: 'Create a care task', exact: true }).getByRole('button', { name: 'Create task', exact: true }).click()
  await expect(page.getByRole('region', { name: /Care tasks/ })).toContainText('Check Pepper at the fence')
  await page.getByLabel('Care note', { exact: true }).fill('Pepper needs a check at the fence.')
  await page.getByRole('button', { name: 'Save and finish', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('[aria-label="Reports"][tabindex="-1"]')).toBeFocused()
  await page.getByRole('combobox', { name: 'Filter by status', exact: true }).selectOption('processed')
  await page.getByRole('button', { name: `Review ${injury}`, exact: true }).click()
  await expect(page.getByRole('region', { name: 'Reviewed details', exact: true })).toContainText('Pepper needs a check at the fence.')
  await expect(page.locator('[data-slot="drawer-content"]').getByRole('textbox')).toHaveCount(0)
  await expect(page.getByRole('region', { name: /Care tasks/ })).toContainText('Open task assigned to Sam Chen')
  await page.getByRole('button', { name: 'Reopen report', exact: true }).click()
  await page.getByRole('combobox', { name: 'Filter by status', exact: true }).selectOption('pending')
  await page.getByRole('button', { name: `Review ${injury}`, exact: true }).click()
  await expect(page.getByLabel('Care note', { exact: true })).toHaveValue('Pepper needs a check at the fence.')
})

