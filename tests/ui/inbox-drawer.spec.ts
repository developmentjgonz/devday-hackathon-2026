for (const width of [320, 390, 768, 1024, 1440]) {
  test(`drawer and nested actions fit ${width}px; the body scrolls without moving the header or footer`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 720 })
    await open(page, 'pages-reports--report-drawer', info.project.name === 'dark')
    const drawer = page.locator('[data-slot="drawer-content"]')
    await expect(drawer).toBeFocused()
    const header = page.locator('[data-slot="drawer-header"]')
    const footer = page.locator('[data-slot="drawer-footer"]')
    const before = { header: await header.boundingBox(), footer: await footer.boundingBox() }
    expect(before.footer!.y + before.footer!.height).toBeLessThanOrEqual(721)
    expect(await drawer.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.getByRole('button', { name: 'Create task', exact: true }).click()
    const task = page.getByRole('dialog', { name: 'Create a care task', exact: true })
    await expect(task).toBeVisible()
    expect(await task.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(header).toHaveCount(1)
    expect(await header.boundingBox()).toEqual(before.header)
    expect(await footer.boundingBox()).toEqual(before.footer)
    expect(await page.locator('[data-slot="drawer-body"]').evaluate((element) => element.scrollTop)).toBeGreaterThan(0)
    for (const key of ['Tab', 'Tab', 'Tab', 'Tab', 'Shift+Tab']) {
      await page.keyboard.press(key)
      await expect.poll(() => drawer.evaluate((element) => element.contains(document.activeElement))).toBe(true)
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}

