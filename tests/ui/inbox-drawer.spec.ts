import { expect, test, type Page } from '@playwright/test'

const injury = 'Possible injury near the feeding station'
const sighting = 'Orange cat by the Canal entrance'
async function open(page: Page, story: string, dark: boolean) {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.addInitScript((dark) => {
    document.addEventListener('DOMContentLoaded', () => document.documentElement.classList.toggle('dark', dark))
  }, dark)
  await page.route('https://images.unsplash.com/**', (route) => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="600" height="400"><rect width="600" height="400" fill="#b6c6ae"/></svg>' }))
  await page.goto(`/iframe.html?id=${story}&viewMode=story`)
}

test('review drafts survive closing, switching reports, and filtering', async ({ page }, info) => {
  await open(page, 'pages-reports--review', info.project.name === 'dark')
  const trigger = page.getByRole('button', { name: `Review ${injury}`, exact: true })
  await trigger.click()
  const drawer = page.locator('[data-slot="drawer-content"]')
  await expect(drawer).toBeFocused()
  await page.getByLabel('Care note', { exact: true }).fill('Arrange a check near Canal.')
  await page.getByLabel('Colony', { exact: true }).selectOption('canal')
  await expect(page.getByLabel('Cat (optional)', { exact: true })).toHaveValue('')
  await page.getByLabel('Cat (optional)', { exact: true }).selectOption('miso')
  await page.getByRole('checkbox', { name: 'Needs urgent attention', exact: true }).uncheck()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await page.getByRole('button', { name: 'Review Three kittens spotted behind the shed', exact: true }).click()
  await expect(page.getByLabel('Care note', { exact: true })).not.toHaveValue('Arrange a check near Canal.')
  await page.keyboard.press('Escape')
  await page.getByLabel('Search reports', { exact: true }).fill('injury')
  await trigger.click()
  await expect(page.getByLabel('Care note', { exact: true })).toHaveValue('Arrange a check near Canal.')
  await expect(page.getByLabel('Colony', { exact: true })).toHaveValue('canal')
  await expect(page.getByLabel('Cat (optional)', { exact: true })).toHaveValue('miso')
  await expect(page.getByRole('checkbox', { name: 'Needs urgent attention', exact: true })).not.toBeChecked()
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Search reports', { exact: true })).toHaveValue('injury')
  await expect(trigger).toBeFocused()
})

