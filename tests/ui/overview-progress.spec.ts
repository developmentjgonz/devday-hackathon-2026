import { expect, test, type Page } from '@playwright/test'

async function openOverview(page: Page, dark: boolean, story = 'progress-overview') {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`/iframe.html?id=pages-my-tasks--${story}&viewMode=story`)
  await page.evaluate((enabled) => document.documentElement.classList.toggle('dark', enabled), dark)
  await expect(page.getByRole('heading', { level: 1, name: 'Overview', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Care progress', exact: true })).toHaveCount(0)
}

test('overview shows open work and recent completions, and updates after completion and undo', async ({ page }, info) => {
  await openOverview(page, info.project.name === 'dark')
  const mine = page.getByRole('region', { name: 'My tasks', exact: true })
  const team = page.getByRole('region', { name: 'Team tasks', exact: true })
  const reports = page.getByRole('region', { name: 'Report reviews', exact: true })
  await expect(mine).toContainText('3 open')
  await expect(mine).toContainText('1 completed in the last 30 days')
  await expect(team).toContainText('4 open')
  await expect(team).toContainText('1 completed in the last 30 days')
  await expect(reports).toContainText('4 need review')
  await expect(reports).toContainText('1 waiting for details')
  const wins = page.getByRole('region', { name: 'Together for the cats' })
  const chart = wins.getByRole('list', { name: 'Tasks completed in the last 30 days by assignee' })
  await expect(wins).toContainText('Your team completed 1 task in the last 30 days.')
  await expect(chart.getByRole('listitem')).toHaveCount(1)
  await expect(chart.getByRole('listitem')).toContainText('Alex Morgan')
  await expect(chart.getByRole('listitem')).toContainText('1 task')
  await expect(page.getByRole('list', { name: 'Tasks', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Team summary', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'View my tasks', exact: true }).click()
  await page.getByRole('button', { name: 'Complete task: Arrange a care check', exact: true }).click()
  await page.getByRole('dialog', { name: 'Complete this task?', exact: true }).getByRole('button', { name: 'Complete task', exact: true }).click()
  await page.getByRole('navigation', { name: 'Workspace navigation', exact: true }).getByRole('link', { name: 'Overview', exact: true }).click()
  await expect(mine).toContainText('2 open')
  await expect(mine).toContainText('2 completed in the last 30 days')
  await expect(team).toContainText('3 open')
  await expect(team).toContainText('2 completed in the last 30 days')
  await expect(reports).toContainText('4 need review')
  await expect(wins).toContainText('Your team completed 2 tasks in the last 30 days.')
  await expect(chart.getByRole('listitem')).toContainText('2 tasks')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(mine).toContainText('3 open')
  await expect(mine).toContainText('1 completed in the last 30 days')
  await expect(team).toContainText('4 open')
  await expect(team).toContainText('1 completed in the last 30 days')
  await expect(wins).toContainText('Your team completed 1 task in the last 30 days.')
  await expect(chart.getByRole('listitem')).toContainText('1 task')
  await page.getByRole('link', { name: 'View my tasks', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'My Tasks', exact: true })).toBeVisible()
})

test('empty task summaries show zero open and recently completed tasks', async ({ page }, info) => {
  await openOverview(page, info.project.name === 'dark', 'no-tasks-overview')
  await expect(page.getByRole('region', { name: 'My tasks', exact: true })).toContainText('0 open')
  await expect(page.getByRole('region', { name: 'My tasks', exact: true })).toContainText('0 completed in the last 30 days')
  await expect(page.getByRole('region', { name: 'Team tasks', exact: true })).toContainText('0 open')
  await expect(page.getByText('No open tasks', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'No recent completions recorded' })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Tasks completed in the last 30 days by assignee' })).toHaveCount(0)
  await expect(page.getByRole('list', { name: 'Tasks', exact: true })).toHaveCount(0)
})

test('dashboard examples show the team’s completed tasks by assignee', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-dashboard--overview&viewMode=story')
  const wins = page.getByRole('region', { name: 'Together for the cats' })
  await expect(wins).toContainText('Your team completed 9 tasks in the last 30 days.')
  const rows = wins.getByRole('list', { name: 'Tasks completed in the last 30 days by assignee' }).getByRole('listitem')
  await expect(rows).toHaveCount(3)
  await expect(rows.nth(0)).toContainText('Alex Morgan')
  await expect(rows.nth(0)).toContainText('4 tasks')
  await expect(rows.nth(1)).toContainText('Maya Rivera')
  await expect(rows.nth(1)).toContainText('3 tasks')
  await expect(rows.nth(2)).toContainText('Sam Chen')
  await expect(rows.nth(2)).toContainText('2 tasks')
})

