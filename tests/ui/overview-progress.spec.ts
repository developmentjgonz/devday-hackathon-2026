  await page.setViewportSize({ width: 320, height: 800 })
  await page.goto('/iframe.html?id=display-bar-chart--long-labels&viewMode=story')
  const chart = page.getByRole('list', { name: 'Completed tasks by assignee' })
  await expect(chart.getByRole('listitem').first()).toContainText('ATeamMemberWithAVeryLongUnbrokenNameAndExtraCharacters')
