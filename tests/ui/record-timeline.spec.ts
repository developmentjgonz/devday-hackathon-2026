import { expect, test } from '@playwright/test'
import { openWorkspaceNavigation } from './state-helpers'
import { confirmTaskCompletion } from './task-confirmation'

test.beforeEach(async ({ page }) => { await page.emulateMedia({ reducedMotion: 'reduce' }) })

const story = '/iframe.html?id=pages-colonies-and-cats--cat&viewMode=story'

for (const width of [390, 1440]) {
  test(`manage a cat task and follow its history at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto(story)
    await page.evaluate((dark) => document.documentElement.classList.toggle('dark', dark), info.project.name === 'dark')
    const timeline = page.getByRole('region', { name: 'Timeline' })

    await page.getByRole('button', { name: 'Edit profile' }).click()
    const profile = page.getByRole('dialog', { name: 'Edit cat profile' })
    await profile.getByLabel('Details (optional)').fill('White paws')
    await profile.getByRole('button', { name: 'Save profile' }).click()
    await expect(timeline.getByText('Cat profile updated')).toBeVisible()
    await expect(timeline).toContainText('White paws')

    await page.getByRole('group', { name: 'Record actions' }).getByRole('button', { name: 'New task' }).click()
    const create = page.getByRole('dialog', { name: 'New task' })
    await expect(create.getByText('Cat: Pepper', { exact: true })).toBeVisible()
    await create.getByLabel('What needs to happen?').fill('Check Pepper’s water')
    await create.getByRole('button', { name: 'Create task' }).click()
    const open = page.getByRole('region', { name: 'Open tasks' })
    await expect(open.getByText('Check Pepper’s water', { exact: true })).toBeVisible()
    await expect(timeline.getByText('Task created: Check Pepper’s water')).toBeVisible()

    for (const dismiss of await page.getByRole('button', { name: 'Dismiss notification' }).all()) await dismiss.click()
    await open.getByRole('link', { name: 'View task: Check Pepper’s water' }).click()
    await page.getByRole('dialog', { name: 'Task', exact: true }).getByRole('button', { name: 'Edit task: Check Pepper’s water' }).click()
    await page.getByRole('dialog', { name: 'Edit task' }).getByRole('button', { name: 'Save task' }).click()
    await page.getByRole('button', { name: 'Close task' }).click()
    await expect(timeline.getByText('Task updated: Check Pepper’s water')).toHaveCount(0)
    for (const dismiss of await page.getByRole('button', { name: 'Dismiss notification' }).all()) await dismiss.click()
    await open.getByRole('link', { name: 'View task: Check Pepper’s water' }).click()
    await page.getByRole('dialog', { name: 'Task', exact: true }).getByRole('button', { name: 'Edit task: Check Pepper’s water' }).click()
    const edit = page.getByRole('dialog', { name: 'Edit task' })
    await edit.getByLabel('What needs to happen?').fill('Refill Pepper’s water')
    await edit.getByRole('button', { name: 'Save task' }).click()
    await page.getByRole('button', { name: 'Close task' }).click()
    await expect(timeline.getByText('Task updated: Refill Pepper’s water')).toBeVisible()
    await open.getByRole('link', { name: 'View task: Refill Pepper’s water' }).click()
    await page.getByRole('dialog', { name: 'Task', exact: true }).getByRole('button', { name: 'Mark complete: Refill Pepper’s water' }).click()
    await confirmTaskCompletion(page, 'Fresh water provided.')
    await page.getByRole('button', { name: 'Close task' }).click()
    const completed = page.getByRole('region', { name: 'Completed tasks' })
    await expect(completed.locator('summary')).toContainText(/Completed tasks\s*\(\d+\)/)
    await expect(completed.getByText('Refill Pepper’s water', { exact: true })).toBeHidden()
    await completed.locator('summary').focus()
    await page.keyboard.press('Enter')
    await expect(completed.getByText('Refill Pepper’s water', { exact: true })).toBeVisible()
    await expect(timeline.getByText('Task completed: Refill Pepper’s water')).toBeVisible()
    await expect(timeline).toContainText('Fresh water provided.')
    await completed.getByRole('link', { name: 'View task: Refill Pepper’s water' }).click()
    await page.getByRole('dialog', { name: 'Task', exact: true }).getByRole('button', { name: 'Reopen task: Refill Pepper’s water' }).click()
    await page.getByRole('button', { name: 'Close task' }).click()
    await expect(open.getByText('Refill Pepper’s water', { exact: true })).toBeVisible()
    await expect(timeline.getByText('Task reopened: Refill Pepper’s water')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)

    const nav = await openWorkspaceNavigation(page)
    await nav.getByRole('link', { name: 'Colonies', exact: true }).click()
    await page.getByRole('link', { name: 'Riverside', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Timeline' }).getByText('Task reopened: Refill Pepper’s water')).toBeVisible()
  })
}

test('task detail actions match the assignee and administrator permissions', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-colonies-and-cats--cat-with-shared-tasks&viewMode=story')
  const tasks = page.getByRole('region', { name: 'Open tasks' })
  const detail = page.getByRole('dialog', { name: 'Task', exact: true })
  await tasks.getByRole('link', { name: 'View task: Check Pepper’s water' }).click()
  await expect(detail.getByRole('button', { name: 'Edit task: Check Pepper’s water' })).toBeVisible()
  await detail.getByRole('button', { name: 'Close task' }).click()
  await tasks.getByRole('link', { name: 'View task: Visit Pepper' }).click()
  await expect(detail.getByRole('button', { name: 'Edit task: Visit Pepper' })).toHaveCount(0)
  await expect(detail.getByRole('button', { name: 'Mark complete: Visit Pepper' })).toHaveCount(0)
  await detail.getByRole('button', { name: 'Close task' }).click()
  await page.goto('/iframe.html?id=pages-colonies-and-cats--cat-with-shared-tasks-as-admin&viewMode=story')
  await tasks.getByRole('link', { name: 'View task: Visit Pepper' }).click()
  await expect(detail.getByRole('button', { name: 'Edit task: Visit Pepper' })).toBeVisible()
  await detail.getByRole('button', { name: 'Mark complete: Visit Pepper' }).click()
  await confirmTaskCompletion(page)
  await detail.getByRole('button', { name: 'Close task' }).click()
  const completed = page.getByRole('region', { name: 'Completed tasks' })
  await completed.locator('summary').click()
  await expect(completed.getByText('Visit Pepper', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(tasks.getByText('Visit Pepper', { exact: true })).toBeVisible()
})

test('a task report link is clear and its drawer supports completion and undo', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-my-tasks--focused-tasks&viewMode=story')
  await page.getByRole('link', { name: 'Open cat: Pepper', exact: true }).click()
  const tasks = page.getByRole('region', { name: 'Open tasks' })
  await tasks.getByRole('link', { name: 'View task: Arrange a care check' }).click()
  const reportLink = page.getByRole('dialog', { name: 'Task', exact: true }).getByRole('link', { name: 'Open report: Possible injury near the feeding station' })
  await expect(reportLink).toHaveCSS('text-decoration-line', 'underline')
  await reportLink.focus()
  await page.keyboard.press('Enter')

  const drawer = page.getByRole('dialog', { name: 'Report', exact: true })
  await drawer.getByRole('button', { name: 'Mark complete: Arrange a care check' }).click()
  await confirmTaskCompletion(page)
  await expect(drawer.getByText('Completed task assigned to Alex Morgan')).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(drawer.getByText('Open task assigned to Alex Morgan')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(reportLink).toBeFocused()
  await page.getByRole('button', { name: 'Close task' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Pepper', exact: true })).toBeVisible()
})

test('record task rows stay aligned when a title wraps on a phone', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/iframe.html?id=pages-colonies-and-cats--cat-with-shared-tasks-as-admin&viewMode=story')
  const tasks = page.getByRole('region', { name: 'Open tasks' })
  await tasks.getByRole('link', { name: 'View task: Check Pepper’s water' }).click()
  await page.getByRole('dialog', { name: 'Task', exact: true }).getByRole('button', { name: 'Edit task: Check Pepper’s water' }).click()
  const edit = page.getByRole('dialog', { name: 'Edit task' })
  const title = 'Check Pepper’s water and bring fresh supplies for the next visit'
  await edit.getByLabel('What needs to happen?').fill(title)
  await edit.getByRole('button', { name: 'Save task' }).click()
  await page.getByRole('button', { name: 'Close task' }).click()
  await page.setViewportSize({ width: 320, height: 700 })
  const first = tasks.getByRole('link', { name: `View task: ${title}` })
  const second = tasks.getByRole('link', { name: 'View task: Visit Pepper' })
  const firstBox = await first.boundingBox()
  const secondBox = await second.boundingBox()
  expect(firstBox).not.toBeNull()
  expect(secondBox).not.toBeNull()
  expect(firstBox!.x + firstBox!.width).toBeCloseTo(secondBox!.x + secondBox!.width, 0)
  await expect(first).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('a failed timeline offers a retry instead of showing an empty history', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-colonies-and-cats--timeline-failure&viewMode=story')
  const timeline = page.getByRole('region', { name: 'Timeline' })
  await expect(timeline.getByRole('heading', { name: 'Timeline unavailable' })).toBeVisible()
  await timeline.getByRole('button', { name: 'Try again' }).click()
  await expect(timeline.getByRole('heading', { name: 'Timeline unavailable' })).toBeVisible()
})
