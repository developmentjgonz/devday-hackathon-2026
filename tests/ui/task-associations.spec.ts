import { expect, test, type Page } from '@playwright/test'

const story = '/iframe.html?id=pages-my-tasks--focused-tasks&viewMode=story'
const nav = (page: Page) => page.getByRole('navigation', { name: 'Workspace navigation' })
const taskCard = (page: Page, title: string) => page.getByRole('list', { name: 'Tasks', exact: true }).locator(':scope > li').filter({ hasText: title })

async function addNamedItem(page: Page, type: string, label: string) {
  const dialog = page.getByRole('dialog', { name: /New task|Edit task/ })
  await dialog.getByLabel('Item type').selectOption(type)
  await dialog.getByLabel(`${type === 'person' ? 'Person' : type === 'paperwork' ? 'Paperwork' : 'Other'} name`).fill(label)
  await dialog.getByRole('button', { name: 'Add related item' }).click()
}

test('standalone tasks can link several kinds of related items and be edited', async ({ page }, info) => {
  await page.goto(story)
  await page.evaluate((dark) => { document.documentElement.classList.toggle('dark', dark); localStorage.removeItem('mews.tasks.view') }, info.project.name === 'dark')
  await page.getByRole('button', { name: 'Cards', exact: true }).click()
  await page.getByRole('region', { name: 'Task controls' }).getByRole('button', { name: 'New task' }).click()
  const dialog = page.getByRole('dialog', { name: 'New task' })
  await dialog.getByLabel('What needs to happen?').fill('Arrange transport for Pepper')
  await dialog.getByLabel('Choose cat').selectOption('pepper')
  await dialog.getByRole('button', { name: 'Add related item' }).click()
  await dialog.getByLabel('Item type').selectOption('colony')
  await dialog.getByLabel('Choose colony').selectOption('canal')
  await dialog.getByRole('button', { name: 'Add related item' }).click()
  await addNamedItem(page, 'person', 'Dr. Lane')
  await addNamedItem(page, 'paperwork', 'Clinic consent form')
  await dialog.getByLabel('Item type').selectOption('other')
  await dialog.getByLabel('Other name').fill('Transport carrier')
  await dialog.getByRole('button', { name: 'Create task' }).click()
  const card = taskCard(page, 'Arrange transport for Pepper')
  await expect(card).toContainText('Pepper')
  await expect(card).toContainText('Riverside')
  await expect(card).toContainText('Canal')
  await expect(card).toContainText('Dr. Lane')
  await expect(card).toContainText('Clinic consent form')
  await expect(card).toContainText('Transport carrier')
  await expect(card.getByRole('link', { name: 'Open cat: Pepper' })).toHaveAttribute('href', '/app/cats/pepper')
  await expect(card.getByRole('link', { name: 'Open colony: Canal' })).toHaveAttribute('href', '/app/colonies/canal')
  await expect(card.getByRole('link', { name: /^Open report:/ })).toHaveCount(0)
  await page.getByLabel('Search my tasks').fill('consent form')
  await expect(taskCard(page, 'Arrange transport for Pepper')).toBeVisible()
  await card.getByRole('button', { name: 'Edit task: Arrange transport for Pepper' }).click()
  const edit = page.getByRole('dialog', { name: 'Edit task' })
  await edit.getByRole('button', { name: 'Remove person: Dr. Lane' }).click()
  await edit.getByRole('button', { name: 'Save task' }).click()
  await expect(card).not.toContainText('Dr. Lane')
  await page.getByLabel('Search my tasks').fill('Dr. Lane')
  await expect(page.getByRole('heading', { name: 'No matching tasks' })).toBeVisible()
  await page.getByLabel('Search my tasks').fill('')
  await card.getByRole('link', { name: 'Open cat: Pepper' }).click()
  await expect(page.getByRole('region', { name: 'Open tasks' })).toContainText('Arrange transport for Pepper')
  await nav(page).getByRole('link', { name: 'Colonies', exact: true }).click()
  await page.getByRole('link', { name: 'Canal', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Open tasks' })).toContainText('Arrange transport for Pepper')
})

test('tasks started from cat records stay visible on the cat and colony', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-colonies-and-cats--cat&viewMode=story')
  await page.getByRole('group', { name: 'Record actions' }).getByRole('button', { name: 'New task' }).click()
  const dialog = page.getByRole('dialog', { name: 'New task' })
  await expect(dialog.getByText('Cat: Pepper', { exact: true })).toBeVisible()
  await dialog.getByLabel('What needs to happen?').fill('Check Pepper’s carrier')
  await dialog.getByRole('button', { name: 'Create task' }).click()
  await expect(page.getByRole('region', { name: 'Open tasks' })).toContainText('Check Pepper’s carrier')
  await page.getByRole('link', { name: 'Riverside', exact: true }).last().click()
  await expect(page.getByRole('region', { name: 'Open tasks' })).toContainText('Check Pepper’s carrier')
  await nav(page).getByRole('link', { name: 'My Tasks', exact: true }).click()
  await expect(page.getByRole('main').getByText('Check Pepper’s carrier', { exact: true })).toBeVisible()
})


test('report tasks keep added and unfinished related items', async ({ page }) => {
  await page.goto(story)
  await page.getByRole('button', { name: 'Cards', exact: true }).click()
  await taskCard(page, 'Arrange a care check').getByRole('link', { name: /^Open report:/ }).click()
  const drawer = page.getByRole('dialog', { name: 'Possible injury near the feeding station' })
  await drawer.getByRole('button', { name: 'Create task' }).click()
  const form = page.getByRole('dialog', { name: 'Create a care task' })
  await form.getByLabel('What needs to happen?').fill('Coordinate a care visit')
  await form.getByLabel('Assign to').selectOption({ label: 'Alex Morgan' })
  await form.getByLabel('Choose cat').selectOption('miso')
  await form.getByRole('button', { name: 'Add related item' }).click()
  await expect(form.getByText('Cat: Miso', { exact: true })).toBeVisible()
  await form.getByLabel('Item type').selectOption('person')
  await form.getByLabel('Person name').fill('Clinic staff')
  await form.getByRole('button', { name: 'Cancel' }).click()
  await drawer.getByRole('button', { name: 'Create task' }).click()
  await expect(form.getByLabel('Person name')).toHaveValue('Clinic staff')
  await form.getByRole('button', { name: 'Create task', exact: true }).click()
  await expect(drawer.getByText('Cat: Miso')).toBeVisible()
  await expect(drawer.getByText('Person: Clinic staff')).toBeVisible()
  await drawer.getByRole('button', { name: 'Close report' }).click()
  await nav(page).getByRole('link', { name: 'My Tasks', exact: true }).click()
  const card = taskCard(page, 'Coordinate a care visit')
  await expect(card).toContainText('Clinic staff')
  await expect(card.getByRole('link', { name: 'Open cat: Miso' })).toBeVisible()
  await expect(card.getByRole('link', { name: 'Open cat: Pepper' })).toBeVisible()
})
