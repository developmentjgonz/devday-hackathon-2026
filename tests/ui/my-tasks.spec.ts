import { expect, test, type Page } from '@playwright/test'
import { confirmTaskCompletion } from './task-confirmation'

test('an unavailable assignee keeps existing tasks and must choose someone for new tasks', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-my-tasks--unavailable-assignee&viewMode=story')
  await page.getByRole('region', { name: 'Task controls' }).getByRole('button', { name: 'New task' }).click()
  const create = page.getByRole('dialog', { name: 'New task' })
  await create.getByLabel('What needs to happen?').fill('Bring food')
  await expect(create.getByLabel('Assign to')).toHaveValue('')
  await expect(create.getByLabel('Assign to').locator('option').filter({ hasText: 'Alex Morgan' })).toHaveCount(0)
  await expect(create.getByRole('button', { name: 'Create task' })).toBeDisabled()
  await create.getByRole('button', { name: 'Cancel' }).click()
  await page.getByRole('button', { name: 'Discard changes' }).click()
  await page.getByRole('button', { name: 'Edit task: Arrange a care check' }).click()
  const edit = page.getByRole('dialog', { name: 'Edit task' })
  await expect(edit.getByLabel('Assign to').locator('option:checked')).toHaveText('Alex Morgan (current assignee)')
  await edit.getByLabel('What needs to happen?').fill('Arrange a care visit')
  await edit.getByRole('button', { name: 'Save task' }).click()
  await expect(page.getByRole('table', { name: 'My tasks' }).getByText('Arrange a care visit', { exact: true })).toBeVisible()
})

async function showList(page: Page) {
  await expect(page.getByRole('table', { name: 'My tasks', exact: true })).toBeVisible()
}

async function openTasks(page: Page, story = 'focused-tasks', dark = false, view: 'cards' | 'list' = 'list') {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`/iframe.html?id=pages-my-tasks--${story}&viewMode=story`)
  await page.evaluate((enabled) => document.documentElement.classList.toggle('dark', enabled), dark)
  await expect(page.getByRole('heading', { level: 1, name: 'My Tasks', exact: true })).toBeVisible()
  if (view === 'list') await showList(page)
}

const taskRows = (page: Page) => page.getByRole('table', { name: 'My tasks', exact: true }).locator('tbody tr')
const taskRow = (page: Page, title: string) => taskRows(page).filter({ has: page.getByText(title, { exact: true }) })
const statusFilter = (page: Page) => page.getByLabel('Filter tasks by status', { exact: true })
const navigation = (page: Page) => page.getByRole('navigation', { name: 'Workspace navigation', exact: true })
const taskCards = (page: Page) => page.getByRole('list', { name: 'Tasks', exact: true }).getByRole('listitem')

for (const view of ['list'] as const) {
  test(`${view} links open the report, cat, and colony; unlinked records have no action`, async ({ page }, info) => {
    await openTasks(page, 'focused-tasks', info.project.name === 'dark', view)
    const item = () => view === 'cards' ? taskCards(page).filter({ has: page.getByRole('heading', { name: 'Arrange a care check', exact: true }) }) : taskRow(page, 'Arrange a care check')
    await expect(item().getByRole('link', { name: 'Open report: Possible injury near the feeding station', exact: true })).toHaveAttribute('href', '/app/reports/report-injury')
    await item().getByRole('link', { name: 'Open cat: Pepper', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: 'Pepper', exact: true })).toBeVisible()
    await navigation(page).getByRole('link', { name: 'My Tasks', exact: true }).click()
    await item().getByRole('link', { name: 'Open colony: Riverside', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: 'Riverside', exact: true })).toBeVisible()
    await navigation(page).getByRole('link', { name: 'My Tasks', exact: true }).click()
    const reportLink = item().getByRole('link', { name: /^Open report:/ })
    await reportLink.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('dialog', { name: 'Report', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('heading', { level: 1, name: 'My Tasks', exact: true })).toBeVisible()
    await expect(reportLink).toBeFocused()
    await openTasks(page, 'unlinked-records', info.project.name === 'dark', view)
    await expect(page.getByRole('link', { name: /^Open report:/ })).toHaveCount(1)
    await expect(page.getByRole('link', { name: /^Open cat:/ })).toHaveCount(0)
    await expect(page.getByRole('link', { name: /^Open colony:/ })).toHaveCount(0)
  })

  test(`${view} completion requires confirmation and supports Undo`, async ({ page }, info) => {
    await openTasks(page, 'focused-tasks', info.project.name === 'dark', view)
    const complete = page.getByRole('button', { name: 'Mark complete: Arrange a care check', exact: true })
    await expect(complete).toHaveText('Mark complete')
    await complete.click()
    const confirmation = page.getByRole('dialog', { name: 'Complete this task?' })
    await expect(confirmation).toContainText('Arrange a care check')
    await confirmation.getByRole('button', { name: 'Cancel' }).click()
    await expect(complete).toBeVisible()
    await complete.click()
    await confirmTaskCompletion(page)
    await expect(complete).toHaveCount(0)
    await expect(page.getByRole('dialog', { name: 'Complete this task?' })).toHaveCount(0)
    await expect(page.getByText('Task completed', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(complete).toBeVisible()
    await expect(page.getByText('Task reopened', { exact: true })).toBeVisible()
  })
}

test('task and report details open over the current page and return to the previous drawer', async ({ page }, info) => {
  await openTasks(page, 'focused-tasks', info.project.name === 'dark', 'cards')
  const taskLink = page.getByRole('link', { name: 'View task: Arrange a care check', exact: true })
  await taskLink.focus()
  await page.keyboard.press('Enter')
  const task = page.getByRole('dialog', { name: 'Task', exact: true })
  await expect(task.getByRole('heading', { name: 'Arrange a care check' })).toBeVisible()
  const reportLink = task.getByRole('link', { name: /^Open report:/ })
  await expect(reportLink).toHaveText('Possible injury near the feeding station')
  await expect(task.getByRole('link', { name: 'Open colony: Riverside' })).toHaveText('Riverside')
  await expect(task.getByRole('link', { name: 'Open cat: Pepper' })).toHaveText('Pepper')
  await reportLink.click()
  const report = page.getByRole('dialog', { name: 'Report', exact: true })
  await expect(report).toBeVisible()
  await report.getByRole('button', { name: 'Close report' }).click()
  await expect(task).toBeVisible()
  await task.getByRole('button', { name: 'Close task' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'My Tasks', exact: true })).toBeVisible()
  await expect(taskLink).toBeFocused()

  await page.getByRole('link', { name: 'Open report: Possible injury near the feeding station', exact: true }).click()
  await report.getByRole('link', { name: 'View task: Arrange a care check', exact: true }).click()
  await expect(task).toBeVisible()
  await task.getByRole('button', { name: 'Close task' }).click()
  await expect(report).toBeVisible()
  await report.getByRole('button', { name: 'Close report' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'My Tasks', exact: true })).toBeVisible()
})

test('dropdown focus is visible for keyboard use without a persistent mouse ring', async ({ page }, info) => {
  await openTasks(page, 'focused-tasks', info.project.name === 'dark', 'cards')
  const filter = statusFilter(page)
  await filter.click()
  await filter.selectOption('all')
  await expect(filter).toBeFocused()
  const pointerShadow = await filter.evaluate((element) => getComputedStyle(element).boxShadow)
  await page.getByRole('searchbox', { name: 'Search my tasks' }).focus()
  await page.keyboard.press('Tab')
  await expect(filter).toBeFocused()
  const keyboardShadow = await filter.evaluate((element) => getComputedStyle(element).boxShadow)
  expect(keyboardShadow).not.toBe(pointerShadow)
})

test('only current-user tasks appear; search and status filters combine', async ({ page }, info) => {
  await openTasks(page, 'focused-tasks', info.project.name === 'dark')
  await expect(page.getByRole('heading', { level: 1 })).toHaveCount(1)
  await expect(page.getByRole('main')).toHaveAccessibleName('My Tasks')
  await expect(navigation(page).getByRole('link', { name: 'My Tasks', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(statusFilter(page)).toHaveValue('open')
  await expect(taskRows(page)).toHaveCount(3)
  await expect(taskRows(page).first()).toContainText('Arrange a care check')
  await expect(taskRows(page).last()).toContainText('Confirm the kitten count')
  await expect(taskRow(page, 'Confirm the kitten count')).toContainText('No due date')
  await expect(page.getByText('Contact the vet', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Confirm evening cover', { exact: true })).toHaveCount(0)
  const search = page.getByRole('searchbox', { name: 'Search my tasks' })
  await search.fill('Canal')
  await expect(taskRows(page)).toHaveCount(1)
  await expect(taskRows(page)).toContainText('Confirm the kitten count')
  await search.fill('Morning feeding')
  await expect(taskRows(page)).toHaveCount(1)
  await expect(taskRows(page)).toContainText('Restock the food container')
  await search.fill('does-not-exist')
  await expect(page.getByRole('heading', { name: 'No matching tasks', exact: true })).toBeVisible()
  await search.clear()
  await statusFilter(page).selectOption('completed')
  await expect(taskRows(page)).toHaveCount(1)
  await expect(taskRows(page)).toContainText('Confirm evening cover')
  await search.fill('does-not-exist')
  await search.clear()
  await expect(statusFilter(page)).toHaveValue('completed')
  await expect(taskRows(page)).toContainText('Confirm evening cover')
  await statusFilter(page).selectOption('all')
  await expect(taskRows(page)).toHaveCount(4)
})

test('complete and reopen survive report navigation without changing report review status', async ({ page }, info) => {
  await openTasks(page, 'focused-tasks', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Mark complete: Arrange a care check', exact: true }).click()
  await confirmTaskCompletion(page)
  await expect(page.getByText('Task completed', { exact: true })).toBeVisible()
  await expect(taskRows(page)).toHaveCount(2)
  await expect(page.getByRole('region', { name: 'My tasks', exact: true })).toBeFocused()
  await statusFilter(page).selectOption('completed')
  const completed = taskRow(page, 'Arrange a care check')
  await expect(completed).toContainText('Completed')
  const reportLink = completed.getByRole('link', { name: 'Open report: Possible injury near the feeding station', exact: true })
  await expect(reportLink).toHaveAttribute('href', '/app/reports/report-injury')
  await reportLink.click()
  const drawer = page.getByRole('dialog', { name: 'Report', exact: true })
  await expect(drawer).toBeVisible()
  await expect(drawer.getByText('Needs review', { exact: true })).toBeVisible()
  await expect(drawer.getByText('Completed task assigned to Alex Morgan', { exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: 'Close report', exact: true }).click()
  await navigation(page).getByRole('link', { name: 'My Tasks', exact: true }).click()
  await showList(page)
  await expect(taskRows(page)).toHaveCount(2)
  await statusFilter(page).selectOption('completed')
  await page.getByRole('button', { name: 'Reopen task: Arrange a care check', exact: true }).click()
  await expect(page.getByText('Task reopened', { exact: true })).toBeVisible()
  await expect(taskRows(page)).toHaveCount(1)
  await statusFilter(page).selectOption('open')
  await expect(taskRows(page)).toHaveCount(3)
  const processed = taskRow(page, 'Restock the food container')
  await processed.getByRole('button', { name: 'Mark complete: Restock the food container', exact: true }).click()
  await confirmTaskCompletion(page)
  await statusFilter(page).selectOption('completed')
  await taskRow(page, 'Restock the food container').getByRole('link', { name: /^Open report:/ }).click()
  const processedDrawer = page.getByRole('dialog', { name: 'Report', exact: true })
  await expect(processedDrawer).toBeVisible()
  await expect(processedDrawer.getByText('Reviewed', { exact: true })).toBeVisible()
  await expect(processedDrawer.getByText('Completed task assigned to Alex Morgan', { exact: true })).toBeVisible()
})

test('tasks created in Reports appear for their assignee in My Tasks', async ({ page }, info) => {
  await openTasks(page, 'focused-tasks', info.project.name === 'dark')
  await taskRow(page, 'Arrange a care check').getByRole('link', { name: /^Open report:/ }).click()
  const drawer = page.getByRole('dialog', { name: 'Report', exact: true })
  await drawer.getByRole('button', { name: 'Create task', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Create a care task', exact: true })
  await dialog.getByLabel('What needs to happen?', { exact: true }).fill('Check the water bowls')
  await dialog.getByLabel('Assign to', { exact: true }).selectOption({ label: 'Alex Morgan' })
  await dialog.getByRole('button', { name: 'Create task', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await drawer.getByRole('button', { name: 'Close report', exact: true }).click()
  await navigation(page).getByRole('link', { name: 'My Tasks', exact: true }).click()
  await showList(page)
  await expect(taskRow(page, 'Check the water bowls')).toBeVisible()
  await expect(taskRows(page)).toHaveCount(4)
})

test('completing the last row on a page returns to the remaining page', async ({ page }, info) => {
  await openTasks(page, 'many-tasks', info.project.name === 'dark')
  await expect(taskRows(page)).toHaveCount(10)
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(taskRows(page)).toHaveCount(1)
  await page.getByRole('button', { name: 'Mark complete: Colony care task 11', exact: true }).click()
  await confirmTaskCompletion(page)
  await expect(taskRows(page)).toHaveCount(10)
  await expect(page.getByText('10 tasks', { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'My tasks', exact: true })).toBeFocused()
})

