import { expect, test, type Page } from '@playwright/test'

async function openTasks(page: Page, story = 'focused-tasks', dark = false) {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`/iframe.html?id=pages-my-tasks--${story}&viewMode=story`)
  await page.evaluate((enabled) => document.documentElement.classList.toggle('dark', enabled), dark)
  await expect(page.getByRole('heading', { level: 1, name: 'My Tasks', exact: true })).toBeVisible()
}

const taskRows = (page: Page) => page.getByRole('table', { name: 'My tasks', exact: true }).locator('tbody tr')
const taskRow = (page: Page, title: string) => taskRows(page).filter({ has: page.getByText(title, { exact: true }) })
const statusFilter = (page: Page) => page.getByLabel('Filter tasks by status', { exact: true })
const navigation = (page: Page) => page.getByRole('navigation', { name: 'Workspace navigation', exact: true })

test('only current-user tasks appear; search and status filters combine', async ({ page }, info) => {
  await openTasks(page, 'focused-tasks', info.project.name === 'dark')
  await expect(page.getByRole('heading', { level: 1 })).toHaveCount(1)
  await expect(page.getByRole('main')).toHaveAccessibleName('My Tasks')
  await expect(navigation(page).getByRole('link', { name: 'My Tasks', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(statusFilter(page)).toHaveValue('open')
  await expect(taskRows(page)).toHaveCount(3)
  await expect(taskRows(page).first()).toContainText('Arrange a care check')
  await expect(taskRows(page).last()).toContainText('Confirm the kitten count')
  await expect(taskRow(page, 'Confirm the kitten count')).toContainText('No due date')
  await expect(page.getByText('Contact the vet', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Confirm evening cover', { exact: true })).toHaveCount(0)
  const search = page.getByRole('searchbox', { name: 'Search my tasks' })
  await search.fill('Canal')
  await expect(taskRows(page)).toHaveCount(1)
  await expect(taskRows(page)).toContainText('Confirm the kitten count')
  await search.fill('Morning feeding')
  await expect(taskRows(page)).toHaveCount(1)
  await expect(taskRows(page)).toContainText('Restock the food container')
  await search.fill('does-not-exist')
  await expect(page.getByRole('heading', { name: 'No matching tasks', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await statusFilter(page).selectOption('completed')
  await expect(taskRows(page)).toHaveCount(1)
  await expect(taskRows(page)).toContainText('Confirm evening cover')
  await statusFilter(page).selectOption('all')
  await expect(taskRows(page)).toHaveCount(4)
})

test('complete and reopen survive report navigation without changing report review status', async ({ page }, info) => {
  await openTasks(page, 'focused-tasks', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Complete task: Arrange a care check', exact: true }).click()
  await expect(page.getByText('Task completed', { exact: true })).toBeVisible()
  await expect(taskRows(page)).toHaveCount(2)
  await expect(page.locator('[data-slot="card"][aria-label="My tasks"]')).toBeFocused()
  await statusFilter(page).selectOption('completed')
  const completed = taskRow(page, 'Arrange a care check')
  await expect(completed).toContainText('Completed')
  const reportLink = completed.getByRole('link', { name: 'Open report: Possible injury near the feeding station', exact: true })
  await expect(reportLink).toHaveAttribute('href', '/app/reports?report=report-injury')
  await reportLink.click()
  const drawer = page.getByRole('dialog', { name: 'Possible injury near the feeding station', exact: true })
  await expect(drawer).toBeVisible()
  await expect(drawer.getByText('Pending', { exact: true })).toBeVisible()
  await expect(drawer.getByText('Completed task assigned to Alex Morgan', { exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: 'Close report', exact: true }).click()
  await navigation(page).getByRole('link', { name: 'My Tasks', exact: true }).click()
  await expect(taskRows(page)).toHaveCount(2)
  await statusFilter(page).selectOption('completed')
  await page.getByRole('button', { name: 'Reopen task: Arrange a care check', exact: true }).click()
  await expect(page.getByText('Task reopened', { exact: true })).toBeVisible()
  await expect(taskRows(page)).toHaveCount(1)
  await statusFilter(page).selectOption('open')
  await expect(taskRows(page)).toHaveCount(3)
  const processed = taskRow(page, 'Restock the food container')
  await processed.getByRole('button', { name: 'Complete task: Restock the food container', exact: true }).click()
  await statusFilter(page).selectOption('completed')
  await taskRow(page, 'Restock the food container').getByRole('link').click()
  const processedDrawer = page.getByRole('dialog', { name: 'Morning feeding and fresh water', exact: true })
  await expect(processedDrawer).toBeVisible()
  await expect(processedDrawer.getByText('Processed', { exact: true })).toBeVisible()
  await expect(processedDrawer.getByText('Completed task assigned to Alex Morgan', { exact: true })).toBeVisible()
})

test('tasks created in Reports appear for their assignee in My Tasks', async ({ page }, info) => {
  await openTasks(page, 'focused-tasks', info.project.name === 'dark')
  await taskRow(page, 'Arrange a care check').getByRole('link').click()
  const drawer = page.getByRole('dialog', { name: 'Possible injury near the feeding station', exact: true })
  await drawer.getByRole('button', { name: 'Create task', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Create a care task', exact: true })
  await dialog.getByLabel('What needs to happen?', { exact: true }).fill('Check the water bowls')
  await dialog.getByLabel('Assign to', { exact: true }).selectOption('Alex Morgan')
  await dialog.getByRole('button', { name: 'Create task', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await drawer.getByRole('button', { name: 'Close report', exact: true }).click()
  await navigation(page).getByRole('link', { name: 'My Tasks', exact: true }).click()
  await expect(taskRow(page, 'Check the water bowls')).toBeVisible()
  await expect(taskRows(page)).toHaveCount(4)
})

test('completing the last row on a page returns to the remaining page', async ({ page }, info) => {
  await openTasks(page, 'many-tasks', info.project.name === 'dark')
  await expect(taskRows(page)).toHaveCount(10)
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(taskRows(page)).toHaveCount(1)
  await page.getByRole('button', { name: 'Complete task: Colony care task 11', exact: true }).click()
  await expect(taskRows(page)).toHaveCount(10)
  await expect(page.getByText('10 tasks', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toHaveCount(0)
  await expect(page.locator('[data-slot="card"][aria-label="My tasks"]')).toBeFocused()
})

test('empty tasks and other assignees have useful states', async ({ page }, info) => {
  await openTasks(page, 'empty', info.project.name === 'dark')
  await expect(page.getByRole('heading', { name: 'No open tasks', exact: true })).toBeVisible()
  await statusFilter(page).selectOption('completed')
  await expect(page.getByRole('heading', { name: 'No completed tasks', exact: true })).toBeVisible()
  await openTasks(page, 'different-assignee', info.project.name === 'dark')
  await expect(taskRows(page)).toHaveCount(1)
  await expect(taskRows(page)).toContainText('Contact the vet')
  await expect(page.getByText('Arrange a care check', { exact: true })).toHaveCount(0)
})

for (const width of [320, 390, 768, 1440]) {
  test(`task content and actions fit ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await openTasks(page, 'long-content', info.project.name === 'dark')
    const complete = page.getByRole('button', { name: /^Complete task:/ })
    await expect(complete).toBeVisible()
    await expect(complete).toBeInViewport()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(await page.getByRole('table', { name: 'My tasks', exact: true }).evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    if (width < 768) {
      await expect(taskRows(page).getByText('Due Nov 8, 2026', { exact: true })).toBeVisible()
      await expect(taskRows(page).getByText('Riverside community garden behind the old railway station', { exact: true }).first()).toBeVisible()
    }
    await complete.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: 'No open tasks', exact: true })).toBeVisible()
    await expect(page.locator('[data-slot="card"][aria-label="My tasks"]')).toBeFocused()
  })
}
