import { expect, test } from '@playwright/test'

test('care rules do not preselect someone who is unavailable for tasks', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-my-tasks--unavailable-care-assignee&viewMode=story')
  await page.getByRole('region', { name: 'Care schedule' }).getByRole('button', { name: 'Add care rule' }).click()
  const create = page.getByRole('dialog', { name: 'Add care rule' })
  await create.getByLabel('What needs to happen?').fill('Refill food')
  await expect(create.getByLabel('Assign to')).toHaveValue('')
  await expect(create.getByRole('button', { name: 'Create rule' })).toBeDisabled()
  await create.getByLabel('Assign to').selectOption({ label: 'Sam Chen' })
  await create.getByRole('button', { name: 'Create rule' }).click()
  await expect(page.getByRole('region', { name: 'Care schedule' })).toContainText('Assigned to Sam Chen')
})

test('a cat care rule creates tasks and can be edited, paused, and resumed', async ({ page }) => {
  await page.goto('/iframe.html?id=pages-colonies-and-cats--cat&viewMode=story')
  const schedule = page.getByRole('region', { name: 'Care schedule' })
  await schedule.getByRole('button', { name: 'Add care rule' }).click()
  const create = page.getByRole('dialog', { name: 'Add care rule' })
  await expect(create.locator('[data-slot="drawer-context"]')).toContainText('Riverside')
  await expect(create.locator('[data-slot="drawer-context"]')).toContainText('Pepper')
  await create.getByLabel('What needs to happen?').fill('Feed Pepper in the morning')
  await create.getByRole('button', { name: 'Create rule' }).click()
  await expect(schedule).toContainText('Feed Pepper in the morning')
  await expect(schedule).toContainText('Every day')
  await expect(page.getByRole('region', { name: 'Open tasks' })).toContainText('Feed Pepper in the morning')

  await schedule.getByRole('button', { name: 'Pause care rule: Feed Pepper in the morning' }).click()
  await expect(schedule).toContainText('Paused')
  await expect(page.getByRole('region', { name: 'Open tasks' })).toContainText('Feed Pepper in the morning')
  await schedule.getByRole('button', { name: 'Edit care rule: Feed Pepper in the morning' }).click()
  const edit = page.getByRole('dialog', { name: 'Edit care rule' })
  await edit.getByLabel('What needs to happen?').fill('Feed Pepper on Mondays')
  await edit.getByLabel('Repeat unit').selectOption('weeks')
  await edit.getByRole('button', { name: 'Save rule' }).click()
  await expect(schedule).toContainText('Every week')
  await schedule.getByRole('button', { name: 'Resume care rule: Feed Pepper on Mondays' }).click()
  await expect(schedule).not.toContainText('Paused')
  await expect(page.getByRole('region', { name: 'Open tasks' })).toContainText('Feed Pepper in the morning')

  await page.getByRole('region', { name: 'Details' }).getByRole('link', { name: 'Riverside' }).click()
  await expect(page.getByRole('region', { name: 'Open tasks' })).toContainText('Feed Pepper in the morning')
  await expect(page.getByRole('region', { name: 'Care schedule' })).not.toContainText('Feed Pepper on Mondays')
})

