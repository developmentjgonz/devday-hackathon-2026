import { expect, test, type Page } from '@playwright/test'
import { openReportFilters, selectReportFilter } from './report-filters'

async function open(page: Page, story: string, dark: boolean) {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.addInitScript((dark) => {
    document.addEventListener('DOMContentLoaded', () => document.documentElement.classList.toggle('dark', dark))
  }, dark)
  await page.goto(`/iframe.html?id=${story}&viewMode=story`)
}

async function showReportList(page: Page) {
  await expect(page.getByRole('table', { name: 'Reports', exact: true })).toBeVisible()
}

test('report filters combine with search, and clearing filters keeps the search', async ({ page }, info) => {
  await open(page, 'pages-reports--focused-inbox', info.project.name === 'dark')
  await showReportList(page)
  const controls = page.getByRole('region', { name: 'Report controls', exact: true })
  const status = page.getByRole('combobox', { name: 'Filter by status', exact: true })
  const colony = page.getByRole('combobox', { name: 'Filter by colony', exact: true })
  const search = controls.getByRole('searchbox', { name: 'Search reports', exact: true })
  const rows = page.locator('[data-slot="table"] tbody tr')
  await expect(page.getByRole('tablist')).toHaveCount(0)
  await expect(controls.getByRole('button', { name: 'Filters (1)' })).toHaveAccessibleDescription('Active filters: 1')
  await expect(controls).toContainText('Status: Needs review')
  await openReportFilters(page)
  await expect(status).toHaveValue('pending')
  await expect(rows).toHaveCount(5)
  await status.selectOption('all')
  await expect(rows).toHaveCount(7)
  await colony.selectOption('canal')
  await page.keyboard.press('Escape')
  await search.fill('Miso')
  await expect(rows).toHaveCount(2)
  await openReportFilters(page)
  await status.selectOption('processed')
  await expect(controls).toContainText('Status: Reviewed · Colony: Canal')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('Miso seen at the Canal entrance')
  await status.selectOption('waiting')
  await expect(page.getByRole('heading', { name: 'No matching reports', exact: true })).toBeVisible()
  await page.getByRole('dialog', { name: 'Filters' }).getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(search).toHaveValue('Miso')
  await expect(rows).toHaveCount(2)
  await expect(page.getByRole('button', { name: 'Filters', exact: true })).toBeFocused()
  await openReportFilters(page)
  await expect(status).toHaveValue('all')
  await expect(colony).toHaveValue('all')
  await page.keyboard.press('Escape')
  await search.fill('')
  await expect(rows).toHaveCount(7)
  await selectReportFilter(page, 'status', 'waiting')
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('Evening feeding cover needed')
})

