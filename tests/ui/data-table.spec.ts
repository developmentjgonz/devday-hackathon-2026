test('delayed page changes retain existing rows and prevent stale interactions', async ({ page }, info) => {
  await open(page, 'display-data-table--delayed-pages', info.project.name === 'dark')
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(10)
  const oldTitle = await page.locator('[data-slot="table"] tbody tr').first().textContent()
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(page.getByRole('status', { name: 'Updating reports', exact: true })).toBeVisible()
  expect(await page.locator('[data-slot="table"] tbody tr').first().textContent()).toBe(oldTitle)
  await expect(page.locator('[inert]')).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByRole('status', { name: 'Updating reports', exact: true })).toHaveCount(0)
  await expect(page.getByText('Page 2 of 4', { exact: true })).toBeVisible()
  expect(await page.locator('[data-slot="table"] tbody tr').first().textContent()).not.toBe(oldTitle)
  await page.getByRole('combobox', { name: 'Rows per page', exact: true }).selectOption('25')
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(25)
  await expect(page.getByRole('navigation', { name: 'Reports pagination' }).getByText('Page 1 of 2', { exact: true })).toBeVisible()
})

