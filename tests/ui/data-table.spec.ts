import { expect, test, type Page } from '@playwright/test'

async function open(page: Page, story: string, dark: boolean) {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.addInitScript((dark) => {
    document.addEventListener('DOMContentLoaded', () => document.documentElement.classList.toggle('dark', dark))
  }, dark)
  await page.goto(`/iframe.html?id=${story}&viewMode=story`)
}

test('sorting applies to all reports and resets pagination', async ({ page }, info) => {
  await open(page, 'pages-inbox--busy-inbox', info.project.name === 'dark')
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(10)
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(page.getByText('Page 2 of 3', { exact: true })).toBeVisible()
  const sort = page.getByRole('button', { name: 'Report', exact: true })
  await sort.focus()
  await page.keyboard.press('Enter')
  await expect(sort.locator('..')).toHaveAttribute('aria-sort', 'ascending')
  await expect(page.getByText('Page 1 of 3', { exact: true })).toBeVisible()
  await expect(page.locator('[data-slot="table"] tbody tr').first()).toContainText('Cat seen near a parking lot')
  await page.keyboard.press('Enter')
  await expect(sort.locator('..')).toHaveAttribute('aria-sort', 'descending')
  await expect(page.locator('[data-slot="table"] tbody tr').first()).toContainText('Three kittens spotted behind the shed')
})

test('opening and marking reports read keeps the current page; filtering resets it', async ({ page }, info) => {
  await open(page, 'pages-inbox--busy-inbox', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  const firstTitle = page.locator('[data-slot="table"] tbody tr').first().locator('[data-slot="table-open-button"]')
  await firstTitle.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Close report', exact: true }).click()
  await expect(firstTitle).toBeFocused()
  await expect(page.getByText('Page 2 of 3', { exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Select this page', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('10 selected', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await page.locator('[data-slot="table"] tbody tr').first().getByRole('checkbox').click()
  await expect(page.getByText('11 selected', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Mark read', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('11 reports marked as read.')
  await expect(page.getByText('Page 3 of 3', { exact: true })).toBeVisible()
  await page.getByLabel('Search reports', { exact: true }).fill('parking lot')
  await expect(page.getByText('Page 1 of 1', { exact: true })).toBeVisible()
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(6)
  await expect(page.locator('[data-slot="table"] tbody tr[aria-selected="true"]')).toHaveCount(0)
  await page.getByLabel('Search reports', { exact: true }).fill('no report matches this phrase')
  await expect(page.getByRole('heading', { name: 'No matching reports', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(10)
})

test('page size and last-page bounds remain correct', async ({ page }, info) => {
  await open(page, 'pages-inbox--busy-inbox', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await page.getByRole('combobox', { name: 'Rows per page', exact: true }).selectOption('25')
  await expect(page.getByText('Page 1 of 2', { exact: true })).toBeVisible()
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(25)
  const height = await page.getByRole('table', { name: 'Reports', exact: true }).locator('..').evaluate((element) => element.clientHeight)
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(5)
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toBeDisabled()
  expect(await page.getByRole('table', { name: 'Reports', exact: true }).locator('..').evaluate((element) => element.clientHeight)).toBe(height)
  await page.getByLabel('Filter by colony', { exact: true }).selectOption('')
  await expect(page.getByText('Page 1 of 1', { exact: true })).toBeVisible()
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(6)
})

test('delayed page changes retain existing rows and prevent stale interactions', async ({ page }, info) => {
  await open(page, 'display-data-table--delayed-pages', info.project.name === 'dark')
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(10)
  const oldTitle = await page.locator('[data-slot="table"] tbody tr').first().textContent()
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(page.getByRole('status', { name: 'Updating reports', exact: true })).toBeVisible()
  expect(await page.locator('[data-slot="table"] tbody tr').first().textContent()).toBe(oldTitle)
  await expect(page.locator('[inert]')).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByRole('status', { name: 'Updating reports', exact: true })).toHaveCount(0)
  await expect(page.getByText('Page 2 of 4', { exact: true })).toBeVisible()
  expect(await page.locator('[data-slot="table"] tbody tr').first().textContent()).not.toBe(oldTitle)
  await page.getByRole('combobox', { name: 'Rows per page', exact: true }).selectOption('25')
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(25)
  await expect(page.getByText('Page 1 of 2', { exact: true })).toBeVisible()
})

test('first load and error retry use the shared loading state', async ({ page }, info) => {
  await open(page, 'display-data-table--loading', info.project.name === 'dark')
  await expect(page.getByRole('status', { name: 'Loading reports', exact: true })).toBeVisible()
  await expect(page.locator('[data-slot="loading-indicator"]')).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Next page', exact: true })).toBeDisabled()
  await open(page, 'display-data-table--error-and-retry', info.project.name === 'dark')
  await page.getByRole('button', { name: 'Try again', exact: true }).click()
  await expect(page.getByRole('status', { name: 'Loading reports', exact: true })).toBeVisible()
  await expect(page.locator('[data-slot="table"] tbody tr')).toHaveCount(10)
  await expect(page.getByText('Page 1 of 4', { exact: true })).toBeVisible()
})

