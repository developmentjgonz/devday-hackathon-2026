test('mobile cards show full titles and review states, and open the review drawer', async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 844 })
  await open(page, 'pages-reports--focused-inbox', info.project.name === 'dark')
  const card = page.getByRole('button', { name: 'Review Three kittens spotted behind the shed', exact: true })
  await expect(card).toBeVisible()
  await expect(card).toHaveAccessibleDescription('Urgent. Needs review. Canal. New sighting.')
  await expect(card).toContainText('Needs review')
  await expect(card).toContainText('Canal · New sighting')
  expect(await card.evaluate((button) => button.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44)
  await card.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Close report', exact: true }).click()
  await expect(card).toBeFocused()
  await expect(card).toContainText('Needs review')
  await page.getByRole('button', { name: 'Sort by title', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sort by title: A–Z', exact: true })).toBeVisible()
  const status = page.getByLabel('Filter by status')
  await status.selectOption('waiting')
  expect(await status.evaluate((element: HTMLSelectElement) => {
    const style = getComputedStyle(element)
    const context = document.createElement('canvas').getContext('2d')!
    context.font = `${style.fontWeight} ${style.fontSize} ${style.fontFamily}`
    const available = element.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight)
    return context.measureText(element.selectedOptions[0]?.textContent ?? '').width <= available
  })).toBe(true)
  await expect(page.getByRole('button', { name: 'Review Evening feeding cover needed', exact: true })).toContainText('Waiting for details')
  await page.getByLabel('Filter by status').selectOption('processed')
  await expect(page.getByRole('button', { name: 'Review Miso seen at the Canal entrance', exact: true })).toContainText('Reviewed')
})
